"""The forecaster through the web editor backend: an NN diagram plus forecaster settings in, a
``forecaster_<model>.py`` file out (``/generate-output`` and ``/generate-output-from-project``).

The diagrams are built as B-UML models and converted with the editor's own NN converter, so the
payload is exactly what the editor sends. Generation needs neither torch nor numpy.
"""
import asyncio
import urllib.parse

import httpx
import pytest

from besser.BUML.metamodel.nn import NN, Configuration, LinearLayer
from besser.utilities.web_modeling_editor.backend.backend import app
from besser.utilities.web_modeling_editor.backend.config import SUPPORTED_GENERATORS
from besser.utilities.web_modeling_editor.backend.services.converters.buml_to_json.nn_diagram_converter import (
    nn_model_to_json,
)
from tests.forecaster_networks import gru, mlp


def _post(url: str, payload: dict) -> httpx.Response:
    async def go():
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://testserver") as ac:
            return await ac.post(url, json=payload)
    return asyncio.run(go())


@pytest.fixture(autouse=True)
def isolate_backend_test_artifacts(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)


def classifier() -> NN:
    model = NN(name="classifier")
    model.add_layer(LinearLayer(name="hidden", in_features=26, out_features=16, actv_func="relu"))
    model.add_layer(LinearLayer(name="output", in_features=16, out_features=3, actv_func="softmax"))
    model.add_configuration(Configuration(batch_size=32, epochs=2, learning_rate=0.003, optimizer="adam",
                                          loss_function="crossentropy", metrics=["accuracy"]))
    return model


def diagram_input(model: NN, config=None) -> dict:
    return {"title": model.name, "model": nn_model_to_json(model), "generator": "forecaster", "config": config}


def project_input(model: NN, config=None) -> dict:
    return {
        "id": "proj-1", "type": "Project", "name": "Forecast", "createdAt": "2026-01-01T00:00:00Z",
        "currentDiagramType": "NNDiagram",
        "diagrams": {"NNDiagram": [{"title": model.name, "model": nn_model_to_json(model)}]},
        "settings": {"generator": "forecaster", "config": config or {}},
    }


def test_the_forecaster_is_registered_for_nn_diagrams():
    info = SUPPORTED_GENERATORS["forecaster"]
    assert info.category == "neural_network"
    assert info.required_diagram_type == "NNDiagram"
    assert info.keep_generated_filename and info.output_type == "file"


def test_an_mlp_with_the_default_settings_becomes_a_forecaster():
    response = _post("/besser_api/generate-output", diagram_input(mlp()))
    assert response.status_code == 200, response.text
    assert 'filename="forecaster_mlp.py"' in response.headers["content-disposition"]
    code = response.text
    assert code.startswith("# Generated by BESSER")
    compile(code, "forecaster_mlp.py", "exec")
    for line in ("WINDOW = 24", "HORIZON = 12", "SEASON = 12", "DIFFERENCE = 12", "SEEDS = [0]"):
        assert line in code


def test_the_settings_reach_the_generated_module():
    config = {"generation_type": "subclassing", "window": 36, "horizon": 6, "season": 4, "log": False,
              "difference": 1, "calendar": True, "standardize": True, "seed": 7}
    response = _post("/besser_api/generate-output", diagram_input(mlp(window=36, horizon=6), config))
    assert response.status_code == 200, response.text
    code = response.text
    for line in ("WINDOW = 36", "HORIZON = 6", "SEASON = 4", "LOG = False", "DIFFERENCE = 1", "CALENDAR = True",
                 "STANDARDIZE = True", "SEEDS = [7]"):
        assert line in code


def test_the_default_difference_follows_the_season():
    response = _post("/besser_api/generate-output", diagram_input(mlp(), {"season": 4}))
    assert response.status_code == 200, response.text
    assert "SEASON = 4" in response.text and "DIFFERENCE = 4" in response.text


def test_a_model_name_outside_latin_1_downloads():
    model = mlp()
    model.name = "数据"
    response = _post("/besser_api/generate-output", diagram_input(model))
    assert response.status_code == 200, response.text
    disposition = response.headers["content-disposition"]
    assert "filename*=UTF-8''" + urllib.parse.quote("forecaster_数据.py") in disposition
    assert 'filename="forecaster.py"' in disposition


def test_a_recurrent_network_through_the_project_endpoint():
    response = _post("/besser_api/generate-output-from-project", project_input(gru(), {"window": 24, "horizon": 12}))
    assert response.status_code == 200, response.text
    assert 'filename="forecaster_gru.py"' in response.headers["content-disposition"]
    compile(response.text, "forecaster_gru.py", "exec")


@pytest.mark.parametrize("config, message", [
    ({"window": 0}, "window must be at least 1"),
    ({"window": "24"}, "window must be an integer"),
    ({"horizon": True}, "horizon must be an integer"),
    ({"log": "yes"}, "log must be true or false"),
    ({"seeds": [1, "2"]}, "seeds must be a list of integers"),
    ({"windw": 24}, "unknown setting(s): windw"),
    ({"channel_last": 1}, "channel_last must be true or false, got int"),
    ({"seed": 1, "seeds": [2]}, "send either seed or seeds, not both"),
    ({"seeds": list(range(1000))}, "at most 100 seeds, not 1000"),
    ({"difference": 5}, "difference must be 0 (levels), 1 (first difference) or the season (12), not 5"),
])
def test_invalid_settings_are_a_400_naming_the_problem(config, message):
    response = _post("/besser_api/generate-output", diagram_input(mlp(), config))
    assert response.status_code == 400
    assert message in response.json()["detail"]


def test_settings_that_do_not_fit_the_network_are_a_400():
    # the network reads 24 + 2 values and returns 12; a 6-month horizon does not match its last layer
    response = _post("/besser_api/generate-output", diagram_input(mlp(), {"horizon": 6}))
    assert response.status_code == 400
    detail = response.json()["detail"]
    assert "NN 'mlp' cannot be generated as a forecaster" in detail
    assert "the last layer 'output' returns 12 values; the horizon is 6, so out_features must be 6" in detail


def test_a_classifier_is_refused_with_a_readable_message():
    response = _post("/besser_api/generate-output", diagram_input(classifier()))
    assert response.status_code == 400
    detail = response.json()["detail"]
    assert "NN 'classifier' cannot be generated as a forecaster" in detail
    assert "a forecaster is trained with the 'mse' loss, not 'crossentropy'" in detail
    assert "the last layer 'output' returns 3 values; the horizon is 12" in detail
    assert "must be linear, not 'softmax'" in detail
