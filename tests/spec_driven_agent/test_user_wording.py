@pytest.mark.parametrize("message, sentence", CASES, ids=[sentence[:40] for _, sentence in CASES])
def test_each_finding_reads_as_one_user_sentence(message, sentence):
    assert user_sentence(message) == sentence
    assert not [fragment for fragment in FORBIDDEN if fragment in sentence]


def test_the_agent_message_still_carries_what_the_agent_needs():
    """Only what the user reads changes: the agent's message keeps its instructions."""
    message = _create_needs_customer()
    assert "test_api" in message and "Fix site" in message and "do not remove business validation" in message


def test_an_unauthorized_create_says_it_needs_signing_in():
    message = _probe({"Note": {"path": "/note/", "verdict": "rejected", "attempts": [
        {"status": 401, "body": "{\"detail\":\"Not authenticated\"}", "outcome": "unauthorized", "payload": {}}]}})[0]
    assert user_sentence(message) == ("Creating note (POST /note/) could not be tested automatically: "
                                      "it requires signing in.")


def test_more_than_five_lines_merge_by_kind_and_say_how_many_more():
    creates = [Finding(f"Creating {name} needs something.", "create_needs", name)
               for name in ("A", "B", "C", "D")]
    others = [Finding(f"Other finding {n}.") for n in range(9)]
    entries = [(finding, finding.sentence) for finding in creates + others]

    lines, covered = summary_lines(entries, 8)

    assert lines[0] == ("4 create operations could not be tested automatically, because each needs an existing "
                        "record first: A, B, C, D.")
    assert len(lines) == 8 and covered == 4 + 7


def test_five_lines_or_fewer_stay_one_per_finding():
    entries = [(Finding(f"Creating {n}.", "create_needs", n), f"Creating {n}.") for n in "AB"]
    assert summary_lines(entries, 8) == (["Creating A.", "Creating B."], 2)


