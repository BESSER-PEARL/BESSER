def test_provenance_file_is_not_counted_as_an_llm_authored_file(tmp_path):
    from besser.utilities.web_modeling_editor.backend.services.spec_driven.telemetry import compute_file_split
    (tmp_path / "main.py").write_text("x = 1\n", encoding="utf-8")
    (tmp_path / PROVENANCE_FILENAME).write_text("# Generated by BESSER\n", encoding="utf-8")
    split = compute_file_split(str(tmp_path), {"main.py"}, set())
    assert split["total"] == 1 and split["llm_authored"] == 0


def test_modify_seed_drops_the_previous_provenance_file(tmp_path):
    from besser.utilities.web_modeling_editor.backend.services.spec_driven.runner import _seed_workspace_from_base
    base, dest = tmp_path / "base", tmp_path / "dest"
    base.mkdir()
    dest.mkdir()
    (base / "main.py").write_text("x = 1\n", encoding="utf-8")
    (base / PROVENANCE_FILENAME).write_text("# Generated by BESSER 0.0.1\n", encoding="utf-8")
    _seed_workspace_from_base(str(base), str(dest))
    assert (dest / "main.py").is_file()
    assert not (dest / PROVENANCE_FILENAME).exists()
