"""A repo whose model an older editor saved, read through the git-backed GitHub stand-in.

Before ``buml/diagrams.json``, the editor's GitHub sidebar saved the bare
project as ``<dir>/<project-name>.json`` (and some repos as
``besser-project.json``). Such a repo linked in today's editor showed no model
and no history, so linking it loaded nothing.
"""

import json

from besser.utilities.web_modeling_editor.backend.services.deployment import repo_model
from tests.utilities.web_modeling_editor.backend.spec_driven.test_model_assembly import CLASS_DIAGRAM_MODEL
from tests.utilities.web_modeling_editor.backend.test_github_round_trip import SESSION, _call, github  # noqa: F401

BARE_PROJECT = {
    "id": "project_1", "type": "Project", "schemaVersion": 5, "name": "OCL_Gen",
    "diagrams": {"ClassDiagram": [{"id": "cd1", "title": "Class Diagram", "model": CLASS_DIAGRAM_MODEL}]},
    "currentDiagramIndices": {"ClassDiagram": 0},
}

# What the old sidebar left in a repo (the user's repo, model replaced).
OLD_SIDEBAR_REPO = {
    "README.md": b"# OCL_Gen\n\n- `ocl_gen.json` - The project definition file\n",
    "ocl_gen.json": json.dumps(BARE_PROJECT).encode(),
    "buml/domain_model.py": b"# Generated by BESSER 8.4.1\n",
}


def _get(path: str, fake, repo: str):
    return _call("GET", f"/besser_api/github/{path}?owner={fake.login}&repo={repo}&branch=main", headers=SESSION)


def _import(fake, repo: str) -> dict:
    response = _call("POST", "/besser_api/spec-driven/import-github-run",
                     json={"owner": fake.login, "repo": repo, "branch": "main"}, headers=SESSION)
    assert response.status_code == 200, response.text
    return response.json()


def _files(fake, repo: str) -> set[str]:
    response = _call("GET", f"/besser_api/github/contents?owner={fake.login}&repo={repo}&path=", headers=SESSION)
    return {item["path"] for item in response.json()["contents"]}


def test_a_repo_the_old_sidebar_saved_shows_and_loads_its_model(github):
    github.create_repo("ocl_gen", files=OLD_SIDEBAR_REPO)

    summary = _get("repo-summary", github, "ocl_gen").json()
    assert summary["has_model"] is True
    assert summary["model_path"] == "ocl_gen.json"
    assert summary["project_name"] == "OCL_Gen"
    assert len(_get("model-history", github, "ocl_gen").json()["commits"]) == 1
    assert _get("project/load", github, "ocl_gen").status_code == 200

    imported = _import(github, "ocl_gen")
    assert imported["has_model"] is True
    assert imported["model_path"] == "ocl_gen.json"
    assert imported["project"]["name"] == "OCL_Gen"


def test_saving_moves_an_old_save_to_buml_diagrams_json(github):
    github.create_repo("ocl_gen", files=OLD_SIDEBAR_REPO)
    head = _get("repo-summary", github, "ocl_gen").json()["head_sha"]

    saved = _call("POST", "/besser_api/github/project/save", headers=SESSION, json={
        "owner": github.login, "repo": "ocl_gen", "branch": "main", "commit_message": "Save OCL_Gen",
        "project_data": BARE_PROJECT, "project_export": {"project": BARE_PROJECT}, "base_commit_sha": head,
        "legacy_file_path": "ocl_gen.json",
    })

    assert saved.status_code == 200, saved.text
    files = _files(github, "ocl_gen")
    assert "ocl_gen.json" not in files
    assert repo_model.MODEL_DIR in files
    assert _get("repo-summary", github, "ocl_gen").json()["model_path"] == repo_model.MODEL_FILE


def test_the_history_reaches_past_the_move_to_buml_diagrams_json(github):
    # Reported: after the first save moved the model, the old sidebar's versions were gone from the history.
    repo = github.create_repo("ocl_gen", files=OLD_SIDEBAR_REPO)
    first = github.ref(repo, "main")
    github.commit_files(repo, {"ocl_gen.json": json.dumps({**BARE_PROJECT, "name": "OCL_Gen v2"})}, "Update OCL_Gen")
    head = _get("repo-summary", github, "ocl_gen").json()["head_sha"]
    saved = _call("POST", "/besser_api/github/project/save", headers=SESSION, json={
        "owner": github.login, "repo": "ocl_gen", "branch": "main", "commit_message": "Save OCL_Gen",
        "project_data": BARE_PROJECT, "project_export": {"project": BARE_PROJECT}, "base_commit_sha": head,
        "legacy_file_path": "ocl_gen.json",
    })
    assert saved.status_code == 200, saved.text

    history = _get("model-history", github, "ocl_gen").json()["commits"]

    assert [entry["message"].split("\n")[0] for entry in history] == [
        "Save OCL_Gen", "Update OCL_Gen", "Initial commit",
    ]
    oldest = _call("GET", f"/besser_api/github/project/load-commit?owner={github.login}&repo=ocl_gen"
                          f"&commit_sha={first}", headers=SESSION)
    assert oldest.json()["project"]["name"] == "OCL_Gen"


def test_a_besser_project_json_repo_loads_and_has_history(github):
    github.create_repo("legacy", files={repo_model.LEGACY_PROJECT_FILE: json.dumps(BARE_PROJECT).encode()})

    assert _import(github, "legacy")["has_model"] is True
    assert len(_get("model-history", github, "legacy").json()["commits"]) == 1


def test_other_json_files_are_not_taken_for_a_model(github):
    github.create_repo("app", files={
        "package.json": b'{"name": "app"}',
        "config/settings.json": b'{"diagrams": "not a dict"}',
        "data/broken.json": b"{ not json",
        "node_modules/x/project.json": json.dumps(BARE_PROJECT).encode(),
    })

    assert _get("repo-summary", github, "app").json()["has_model"] is False
    assert _import(github, "app")["has_model"] is False


def test_a_repo_with_several_models_lists_them_and_reads_the_one_picked(github):
    current = {"project": {**BARE_PROJECT, "name": "Current"}}
    github.create_repo("two", files={
        repo_model.MODEL_FILE: json.dumps(current).encode(),
        "ocl_gen.json": json.dumps(BARE_PROJECT).encode(),
    })
    picked = "&model_path=ocl_gen.json"

    summary = _get("repo-summary", github, "two").json()
    assert summary["model_paths"] == [repo_model.MODEL_FILE, "ocl_gen.json"]
    assert (summary["model_path"], summary["project_name"]) == (repo_model.MODEL_FILE, "Current")
    assert _get("repo-summary", github, "two" + picked).json()["project_name"] == "OCL_Gen"
    assert _get("project/load", github, "two" + picked).json()["project"]["name"] == "OCL_Gen"
    assert len(_get("model-history", github, "two" + picked).json()["commits"]) == 1

    response = _call("POST", "/besser_api/spec-driven/import-github-run", headers=SESSION, json={
        "owner": github.login, "repo": "two", "branch": "main", "model_path": "ocl_gen.json",
    })
    assert (response.json()["model_path"], response.json()["project"]["name"]) == ("ocl_gen.json", "OCL_Gen")


def test_a_picked_file_that_is_gone_falls_back_to_the_repo_model(github):
    # The link remembers ocl_gen.json; a teammate's save since replaced it with buml/diagrams.json.
    github.create_repo("moved", files={repo_model.MODEL_FILE: json.dumps({"project": BARE_PROJECT}).encode()})
    gone = "&model_path=ocl_gen.json"

    assert _get("project/load", github, "moved" + gone).status_code == 200
    assert len(_get("model-history", github, "moved" + gone).json()["commits"]) == 1
    response = _call("POST", "/besser_api/spec-driven/import-github-run", headers=SESSION, json={
        "owner": github.login, "repo": "moved", "model_path": "ocl_gen.json",
    })
    assert (response.json()["has_model"], response.json()["model_path"]) == (True, repo_model.MODEL_FILE)


def test_a_model_path_outside_the_repo_is_refused(github):
    github.create_repo("ocl_gen", files=OLD_SIDEBAR_REPO)

    assert _get("project/load", github, "ocl_gen&model_path=../secrets.json").status_code == 400
    for model_path in ("/etc/passwd.json", "../secrets.json", "buml/../../secrets.json"):
        response = _call("POST", "/besser_api/spec-driven/import-github-run", headers=SESSION, json={
            "owner": github.login, "repo": "ocl_gen", "model_path": model_path,
        })
        assert response.status_code == 422
        assert "model_path must be a relative repo path to a .json file" in response.json()["detail"][0]["msg"]


