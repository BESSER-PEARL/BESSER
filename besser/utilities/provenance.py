"""
Provenance of generated output: which BESSER version produced it.

The version is the package version from ``setup.cfg``, and the build commit is
``BESSER_BUILD_SHA`` when the Docker build set it. The provenance
file carries no timestamp, so regenerating the same model yields the same bytes.
"""
import configparser
import io
import os
import re
import zipfile
from functools import lru_cache
from importlib import metadata
from pathlib import Path
from typing import Mapping, Optional
from urllib.parse import quote

PROVENANCE_FILENAME = "BESSER_GENERATION.md"
BESSER_URL = "https://github.com/BESSER-PEARL/BESSER"
EDITOR_URL = "https://editor.besser-pearl.org"
CATALOG_URL = "https://github.com/BESSER-PEARL/Built-with-BESSER"
README_FILENAME = "README.md"
README_BLOCK_BEGIN = "<!-- besser:begin -->"
README_BLOCK_END = "<!-- besser:end -->"
_README_BLOCK = re.compile(re.escape(README_BLOCK_BEGIN) + r".*?" + re.escape(README_BLOCK_END), re.DOTALL)


@lru_cache(maxsize=1)
def get_besser_version() -> str:
    """The version of the BESSER code that is running, or ``"unknown"``.

    A source checkout (editable install, Docker image) reads the ``setup.cfg``
    beside the package: package metadata found on ``sys.path`` can belong to
    another install. A wheel install has no ``setup.cfg`` and uses its metadata.
    """
    setup_cfg = Path(__file__).resolve().parents[2] / "setup.cfg"
    if setup_cfg.is_file():
        parser = configparser.ConfigParser()
        parser.read(setup_cfg, encoding="utf-8")
        version = parser.get("metadata", "version", fallback="").strip()
        if version and parser.get("metadata", "name", fallback="") == "besser":
            return version
    try:
        return metadata.version("besser")
    except metadata.PackageNotFoundError:
        return "unknown"


def get_build_sha() -> Optional[str]:
    """The commit the Docker image was built from, or None when not stamped."""
    sha = os.environ.get("BESSER_BUILD_SHA", "").strip()
    return sha if sha and sha != "unknown" else None


def _inline(value) -> str:
    """Keep a value on one line and inside its backticks."""
    return " ".join(str(value).split()).replace("`", "'")


def generation_provenance_markdown(
    generator: str,
    options: Optional[Mapping[str, object]] = None,
) -> str:
    """The ``BESSER_GENERATION.md`` text for one generation.

    ``options`` must hold only user-facing settings that shape the output
    (dbms, project name, ...), never credentials.
    """
    lines = [
        "# Generated by BESSER",
        "",
        f"This code was generated by [BESSER]({BESSER_URL}), a low-code, model-driven platform.",
        "",
        f"- BESSER version: `{_inline(get_besser_version())}`",
    ]
    build_sha = get_build_sha()
    if build_sha:
        lines.append(f"- BESSER build: `{_inline(build_sha)}`")
    lines.append(f"- Generator: `{_inline(generator)}`")
    shown = {k: v for k, v in (options or {}).items() if v is not None and v != ""}
    if shown:
        lines.append("- Options:")
        lines.extend(f"  - {_inline(k)}: `{_inline(v)}`" for k, v in shown.items())
    lines += [
        "",
        "Regenerating from the model overwrites these files; re-apply any manual changes afterwards.",
        "",
        f"If BESSER saved you time, a [star on GitHub]({BESSER_URL}) helps others find it.",
        "",
    ]
    return "\n".join(lines)


def write_generation_provenance(
    directory: str,
    generator: str,
    options: Optional[Mapping[str, object]] = None,
) -> str:
    """Write ``BESSER_GENERATION.md`` at the root of ``directory``; returns its path."""
    from besser.spec_driven_agent.execution.workspace_fs import open_plain_write

    path = os.path.join(directory, PROVENANCE_FILENAME)
    # A run workspace can hold a link at this name; never write through it.
    with open_plain_write(path, "w", root=directory, encoding="utf-8", newline="\n") as handle:
        handle.write(generation_provenance_markdown(generator, options))
    return path


def readme_besser_block(
    owner: str,
    repo: str,
    branch: str,
    model_source: Optional[str] = None,
    has_provenance: bool = False,
) -> str:
    """The "Built with BESSER" block a GitHub push keeps at the end of the README.

    ``model_source`` is the repo path of a B-UML file the editor's ``?buml=``
    link can open; without one the block links no model.
    """
    lines = [
        README_BLOCK_BEGIN,
        "---",
        "",
        f"[![Built with BESSER](https://img.shields.io/badge/Built_with-BESSER-2563eb)]({BESSER_URL})",
        "",
    ]
    if model_source:
        model_dir = model_source.rsplit("/", 1)[0]
        lines.append(f"Generated by [BESSER]({BESSER_URL}), the open-source low-code, model-driven platform, "
                     f"from the B-UML model in [`{model_dir}/`]({model_dir}/).")
    else:
        lines.append(f"Generated by [BESSER]({BESSER_URL}), the open-source low-code, model-driven platform.")
    links = []
    if model_source:
        blob = f"https://github.com/{owner}/{repo}/blob/{branch}/{model_source}"
        links.append(f"[Open the model in the BESSER editor]({EDITOR_URL}/?buml={quote(blob, safe=':/')})")
    links.append(f"[More apps built with BESSER]({CATALOG_URL})")
    if has_provenance:
        links.append(f"[Generation details]({PROVENANCE_FILENAME})")
    lines += ["", " · ".join(links), README_BLOCK_END]
    return "\n".join(lines)


def strip_readme_block(text: str) -> str:
    """``text`` without the BESSER block and the blank lines around it."""
    match = _README_BLOCK.search(text)
    if not match:
        return text
    before, after = text[:match.start()].rstrip(), text[match.end():].lstrip("\r\n")
    newline = "\r\n" if "\r\n" in text else "\n"
    if after.strip():
        return f"{before}{newline}{newline}{after}" if before else after
    return f"{before}{newline}" if before else ""


def with_readme_block(text: str, block: str) -> str:
    """``text`` with ``block`` in place of its BESSER block, or appended when it has none."""
    newline = "\r\n" if "\r\n" in text else "\n"
    block = block.replace("\n", newline)
    if _README_BLOCK.search(text):
        return _README_BLOCK.sub(lambda _: block, text, count=1)
    body = text.rstrip()
    return f"{body}{newline}{newline}{block}{newline}" if body else f"{block}{newline}"


def _root_readme(directory: str) -> Optional[str]:
    """The root README.md of ``directory``, whatever its case, or None."""
    for name in sorted(os.listdir(directory)):
        if name.lower() == README_FILENAME.lower() and os.path.isfile(os.path.join(directory, name)):
            return os.path.join(directory, name)
    return None


def _read_text(path: str, root: str) -> Optional[str]:
    from besser.spec_driven_agent.execution.workspace_fs import open_plain

    try:
        with open_plain(path, "rb", root=root) as handle:
            return handle.read().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _write_text(path: str, root: str, text: str) -> None:
    from besser.spec_driven_agent.execution.workspace_fs import open_plain_write

    with open_plain_write(path, "wb", root=root) as handle:
        handle.write(text.encode("utf-8"))


def add_readme_block(directory: str, block: str, title: Optional[str] = None) -> None:
    """Put ``block`` into the root README of ``directory``.

    A missing README is created as ``# title`` only when ``title`` is given: in an
    existing repo it would replace the README the repo already has. A README
    that is not UTF-8 text is left as it is.
    """
    path = _root_readme(directory)
    if path is None:
        if title is None:
            return
        path, text = os.path.join(directory, README_FILENAME), f"# {title}\n"
    else:
        text = _read_text(path, directory)
        if text is None:
            return
    _write_text(path, directory, with_readme_block(text, block))


def remove_readme_block(directory: str) -> None:
    """Drop the BESSER block from the root README of ``directory``, if it has one.

    The push renders the block again; removing it first keeps it out of the
    agent's view and out of the line attribution of a run seeded from the repo.
    """
    path = _root_readme(directory)
    text = _read_text(path, directory) if path else None
    if text is not None and _README_BLOCK.search(text):
        _write_text(path, directory, strip_readme_block(text))


def add_generation_provenance_to_zip(
    zip_buffer: io.BytesIO,
    generator: str,
    options: Optional[Mapping[str, object]] = None,
) -> io.BytesIO:
    """Append ``BESSER_GENERATION.md`` to the root of an in-memory zip, unless present."""
    zip_buffer.seek(0)
    with zipfile.ZipFile(zip_buffer, "a", zipfile.ZIP_DEFLATED) as archive:
        if PROVENANCE_FILENAME not in archive.namelist():
            # A fixed date keeps the entry itself byte-identical across runs.
            info = zipfile.ZipInfo(PROVENANCE_FILENAME, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, generation_provenance_markdown(generator, options))
    zip_buffer.seek(0)
    return zip_buffer
