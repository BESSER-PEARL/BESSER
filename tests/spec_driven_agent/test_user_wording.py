"""What the user reads about verification is written for the user.

The run card, ``BESSER_GENERATION.md`` and the incomplete notice used to show a
validator finding verbatim: instructions to the coding agent ("Use test_api
...", "do not remove business validation ..."), the request payload the probe
sent and the file and line to edit. Each message below is built by the code
that writes it for the agent, and must come out as one plain sentence.
"""
