def _post(payload):
    async def _request():
        async with httpx.AsyncClient(transport=ASGITransport(app=app), base_url="http://testserver") as client:
            return await client.post("/besser_api/generate-output", json=payload)
    return asyncio.run(_request())


def _generate(generator, config=None):
    response = _post({"title": "Library", "model": CLASS_MODEL, "generator": generator, "config": config})
    assert response.status_code == 200, response.text
    return response


def _zip_entries(content: bytes) -> dict:
    with zipfile.ZipFile(io.BytesIO(content)) as archive:
        return {name: archive.read(name) for name in archive.namelist()}


