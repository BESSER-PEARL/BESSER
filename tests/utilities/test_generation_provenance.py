"""The BESSER version is recorded in generated output (issue #617).

- Web-editor zips carry ``BESSER_GENERATION.md`` (version, generator, options, no secrets).
- Single-file downloads carry a leading version comment where the file type allows one.
- B-UML exports start with ``# Generated by BESSER <version>`` and still load back.
- Spec-Driven runs record the version in the recipe and ship the same provenance file.
"""

