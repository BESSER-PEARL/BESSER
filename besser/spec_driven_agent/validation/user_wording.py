"""Validator findings in words for the person who asked for the app.

A finding's message is written for the coding agent: what to call next, what
not to delete, the request payload and the file and line to edit. That message
stays as it is for the agent, the trace and the recipe's ``validation_issues``.
What the user reads (the run card, ``BESSER_GENERATION.md``, the incomplete
notice) is one short sentence per finding, built here from the same prefixes
``issues._classify_issue`` keys on. A kind without its own sentence gets a
generic one, never the agent's text.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from besser.spec_driven_agent.validation.issues import _TRUNCATION_NOTE_RE, _classify_issue

# The app's own refusal and a requirement's text are quoted; longer is cut.
_MAX_QUOTED = 100
_MAX_REQUIREMENT = 160

GENERIC_SENTENCE = "An automatic check reported a problem; the run's detailed report lists it."


@dataclass(frozen=True)
class Finding:
    """One finding for the user: its sentence, and how it merges with its kind."""

    sentence: str
    group: str = ""
    subject: str = ""


# Several findings of one group read as one line: "{n}" and "{subjects}" are filled in.
GROUP_SENTENCES = {
    "create_needs": "{n} create operations could not be tested automatically, because each needs "
                    "an existing record first: {subjects}.",
    "create_refused": "{n} create operations were refused with the test data used: {subjects}.",
    "create_untested": "{n} create operations could not be tested automatically: {subjects}.",
    "create_failed": "{n} create operations failed with a server error in the test run: {subjects}.",
    "action_untested": "{n} actions could not be tested automatically: {subjects}.",
    "action_failed": "{n} actions failed or changed nothing in the test run: {subjects}.",
    "requirement_unconfirmed": "{n} requirements could not be confirmed in the code: {subjects}.",
    "task_unconfirmed": "{n} planned changes could not be confirmed as done.",
    "workflow_failed": "{n} test workflows ran and failed: {subjects}.",
    "no_create_screen": "The user interface offers no way to create: {subjects}.",
    "operation_missing": "{n} operations of the model are not implemented: {subjects}.",
}

# Checks named by their internal tool, said in plain words.
_CHECK_NAMES = (
    ("the constructibility probe", "the automatic create test"),
    ("constructibility probe", "automatic create test"),
    ("the acceptance matrix", "the check of the app's screens"),
    ("runtime probe", "test run of the app"),
    ("the requirements judge", "the check against your request"),
)

_PATH_PARAM = re.compile(r"^\{.*\}$")
_REQUIREMENT = re.compile(r"^R(?P<id>\d+) — (?P<rest>.*)$", re.S)
# What ``requirements_ledger.ledger_issues`` puts after a requirement's text; its note comes last, as " (...)".
_REQUIREMENT_ENDS = (" — the cited evidence ", " is not implemented", "; inspect and complete the missing behaviour")
# An absolute path in a check's reason: a server's workspace, never the user's.
_ABSOLUTE_PATH = re.compile(r"(?<![\w.])(?:[A-Za-z]:)?[\\/](?:[^\s'\"\\/]+[\\/])+[^\s'\")]*")
_ROUTE = re.compile(r"\b(?P<method>GET|POST|PUT|PATCH|DELETE) (?P<path>/\S*)")
_UNRESOLVED = re.compile(r"unresolved related IDs: (\[.*?\]\])")
_REFUSED = re.compile(r"autogenerated input was refused \((?P<status>\d+): (?P<body>.*?)\); attempted input:", re.S)
_DEPENDENTS = re.compile(r"Dependent create probes for .*? could not run without a (?P<name>\w+) id")
_ACTION = re.compile(r"POST \S+ - (?P<action>\w+) (?:on (?P<entity>\w+)|answered)")
_ACTION_CALLING = re.compile(r"failure calling (?P<action>\w+) on a (?P<entity>\w+)")
_ACTION_ENTITY = re.compile(r"the (?P<entity>\w+) created one request earlier")
_SCENARIO = re.compile(r"^api scenario: (?P<id>.+?) failed:")
_TASK = re.compile(r"remains unresolved: (?P<text>.*?)\.(?: |$)", re.S)
_DID_NOT_RUN = re.compile(r"^validation(?: unverified)?: (?P<check>.+?) did not run(?: completely)?"
                          r"(?: \((?P<reason>.*?)\))?(?: - |$)")
_DETAIL_TEXT = re.compile(r'"detail"\s*:\s*"((?:[^"\\]|\\.)+)"')
_ERROR_MSG = re.compile(r'"loc"\s*:\s*\[(?P<loc>[^\]]*)\].*?"msg"\s*:\s*"(?P<msg>(?:[^"\\]|\\.)+)"', re.S)
_ACCEPTANCE = re.compile(r"^acceptance: entity (?P<entity>\w+) — (?P<detail>.*)")

# Prefixes whose finding needs no detail to be said plainly.
_SIMPLE = (
    ("syntax error in", "A source file does not parse, so the app cannot run."),
    ("dependency conflict in", "The app's listed dependencies conflict and cannot all be installed."),
    ("frontend contract:", "The user interface has a defect that leaves part of it unusable."),
    ("api url:", "A form in the user interface does not send its data to the right place."),
    ("form create target:", "A form in the user interface does not send its data to the right place."),
    ("form route:", "A form in the user interface cannot be reached."),
    ("form json textarea:", "A form in the user interface asks for raw data instead of fields."),
    ("form field type:", "A form field does not match the type of value it collects."),
    ("api call:", "A screen sends a request, or reads its answer, in a shape the backend does not use."),
    ("data contract", "The code does not match the class diagram (an identifier or a field type)."),
    ("model conformance:", "The backend does not match the latest changes to the class diagram."),
    ("missing module:", "The code imports a module that is not in the output, so the app cannot start."),
    ("mapper config:", "The database layer does not load, so requests that use the database fail."),
    ("application startup:", "The app does not start."),
    ("python contract:", "The backend code has a defect that stops part of it from running."),
    ("open account writes:", "A route lets a request change records it should not be allowed to change."),
    ("verification setup:", "The app's dependencies were not installed, so some checks could not run."),
    ("runtime gate:", "The app could not be shown to start and save a record."),
    ("entity coverage:", "Not every class can be created, viewed, edited and deleted in the app."),
    ("requirement out of scope:", "A requirement was judged to be outside what this app covers."),
    ("requirement not provable:", "A requirement cannot be shown by reading the code (something the app must not "
                                  "have, or behaviour kept as before), so it is not counted as a blocker."),
    ("reported-failure:", "The failure you reported could not be confirmed as fixed."),
    ("tsc [", "The user interface does not compile."),
    ("frontend build [", "The user interface does not build."),
    ("cargo [", "The code does not compile."),
    ("kotlinc [", "The code does not compile."),
)


def _cut(text: str, limit: int) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else (text[:limit].rsplit(" ", 1)[0] or text[:limit]) + "…"


def plain_check(name: str) -> str:
    """A check's name without the internal tool vocabulary."""
    runtime = re.fullmatch(r"runtime check \((.+)\)", name)
    name = runtime.group(1) if runtime else name
    for internal, plain in _CHECK_NAMES:
        name = name.replace(internal, plain)
    scenario = re.match(r"api scenario (.+)", name)
    return f"the test workflow '{scenario.group(1)}'" if scenario else name


def plain_reason(reason: str) -> str:
    """A check's reason for not running, without the server paths it may name."""
    return _cut(_ABSOLUTE_PATH.sub("…", reason), _MAX_REQUIREMENT)


def _requirement_text(rest: str) -> str:
    for end in _REQUIREMENT_ENDS:
        rest = rest.split(end, 1)[0]
    if rest.endswith(")"):  # the judge's note: cut at the parenthesis that the last one closes
        depth = 0
        for index in range(len(rest) - 1, -1, -1):
            depth += {")": 1, "(": -1}.get(rest[index], 0)
            if depth == 0:
                rest = rest[:index].rstrip() if index and rest[index - 1] == " " else rest
                break
    return _cut(rest, _MAX_REQUIREMENT)


def _route_subject(path: str) -> str:
    """``/orders/`` -> ``orders``; ``/order/{id}/items/`` -> ``items``."""
    parts = [part for part in path.split("?", 1)[0].split("/") if part and not _PATH_PARAM.match(part)]
    return parts[-1] if parts else path


def _app_reason(body: str) -> str:
    """The app's own words for a refusal (FastAPI's ``detail``), or "" when it gave none.

    The probe keeps only the start of a body, so a validation error often
    arrives as cut JSON: its first ``loc`` and ``msg`` are read from the text.
    """
    try:
        detail = json.loads(body).get("detail")
    except (ValueError, AttributeError):
        detail = (_DETAIL_TEXT.search(body) or [None, None])[1]
        msg = _ERROR_MSG.search(body)
        if detail is None and msg:
            detail = [{"loc": re.findall(r'"([^"]*)"', msg.group("loc")), "msg": msg.group("msg")}]
    if isinstance(detail, list) and detail and isinstance(detail[0], dict):
        first = detail[0]
        field = ".".join(str(part) for part in first.get("loc") or [] if part != "body")
        detail = f"{field}: {first.get('msg')}" if field else first.get("msg")
    if isinstance(detail, str) and detail:
        return _cut(detail, _MAX_QUOTED)
    return "" if body.lstrip().startswith(("{", "[")) else _cut(body, _MAX_QUOTED)


def _create(message: str) -> Finding:
    route = _ROUTE.search(message)
    path = route.group("path") if route else ""
    named = _DEPENDENTS.search(message)
    subject = named.group("name") if named else _route_subject(path)
    what = f"Creating {subject} (POST {path})" if path else f"Creating {subject}"
    if message.startswith("create contract:"):
        return Finding(f"{what} failed with a server error in the test run.", "create_failed", subject)
    unresolved = _UNRESOLVED.search(message)
    if unresolved:
        try:
            targets = sorted({str(pair[1]) for pair in json.loads(unresolved.group(1)) if len(pair) > 1})
        except (ValueError, TypeError):
            targets = []
        if targets:
            return Finding(f"{what} could not be tested automatically: it needs an existing "
                           f"{' and an existing '.join(targets)} first.", "create_needs", subject)
    if "requires authentication" in message:
        return Finding(f"{what} could not be tested automatically: it requires signing in.",
                       "create_untested", subject)
    refused = _REFUSED.search(message)
    if refused:
        reason = _app_reason(refused.group("body"))
        return Finding(f"{what} was refused with the test data used" + (f" ({reason})." if reason else "."),
                       "create_refused", subject)
    return Finding(f"{what} could not be tested automatically.", "create_untested", subject)


def _action(message: str) -> Finding:
    found = _ACTION_CALLING.search(message) or _ACTION.search(message)
    action = found.group("action") if found else "an action"
    entity = found.group("entity") if found else None
    if entity is None and (match := _ACTION_ENTITY.search(message)):
        entity = match.group("entity")
    subject = f"{action} on {entity}" if entity else action
    if "declared failure" in message:
        return Finding(f"The action {subject} reported a failure and changed nothing in the test run.",
                       "action_failed", subject)
    if message.startswith("action call:"):
        return Finding(f"The action {subject} failed with a server error in the test run.",
                       "action_failed", subject)
    return Finding(f"The action {subject} could not be tested automatically: it refused every state "
                   "the test could set up.", "action_untested", subject)


def _requirement(message: str, prefix: str) -> Finding:
    body = message[len(prefix):].strip()
    found = _REQUIREMENT.match(body)
    if found is None:
        if "extraction failed" in body:
            return Finding("Your request could not be turned into checkable requirements, so the result "
                           "was not checked against it.")
        if "budget exhausted" in body or "verification stopped" in body:
            return Finding("Checking the result against your request stopped before it finished.")
        if "did not run" in body:
            return Finding("The final checks of the app did not run.")
        return Finding("A requirement of your request could not be checked.")
    ident, text = f"R{found.group('id')}", _requirement_text(found.group("rest"))
    if prefix == "requirement:":
        return Finding(f"Requirement {ident} is not implemented: {text}")
    if prefix == "requirement partial:":
        return Finding(f"Requirement {ident} is only partly implemented: {text}")
    return Finding(f"Requirement {ident} could not be confirmed in the code: {text}",
                   "requirement_unconfirmed", ident)


def user_finding(message: str) -> Finding:
    """One finding, said for the user."""
    text = " ".join(str(message or "").split())
    if text.startswith("runtime unverified: "):
        text = text[len("runtime unverified: "):]
    lower = text.lower()
    if lower.startswith(("create unverified:", "create contract:")):
        return _create(text)
    if lower.startswith(("action unverified:", "action call:")):
        return _action(text)
    for prefix in ("requirement unverified:", "requirement partial:", "requirement:"):
        if lower.startswith(prefix):
            return _requirement(text, prefix)
    if lower.startswith("task unverified:"):
        task = _TASK.search(text)
        return Finding("A planned change could not be confirmed as done"
                       + (f": {_cut(task.group('text'), _MAX_REQUIREMENT)}" if task else "."),
                       "task_unconfirmed")
    if scenario := _SCENARIO.match(text):
        name = scenario.group("id")
        return Finding(f"The test workflow '{name}' ran and failed.", "workflow_failed", name)
    if skipped := _DID_NOT_RUN.match(text):
        check = plain_check(skipped.group("check"))
        if check.startswith("the test workflow "):
            return Finding(f"{check[0].upper()}{check[1:]} could not be run against the app.")
        reason = f" ({plain_reason(skipped.group('reason'))})" if skipped.group("reason") else ""
        return Finding(f"Not run: {check}{reason}, so its checks are not covered.")
    if acceptance := _ACCEPTANCE.match(text):
        entity = acceptance.group("entity")
        if "create" in acceptance.group("detail"):
            return Finding(f"The user interface offers no way to create a {entity}.", "no_create_screen", entity)
        return Finding(f"{entity} has no screen or route of its own in the app.")
    if lower.startswith("action contract:"):
        route = _ROUTE.search(text)
        operation = f"{route.group('method')} {route.group('path')}" if route else "an operation"
        return Finding(f"The operation {operation} of the model is not implemented.", "operation_missing",
                       operation)
    if lower.startswith("model contract:"):
        return Finding("The class diagram has a problem the generated code cannot resolve: "
                       + _cut(text[len("model contract:"):], _MAX_REQUIREMENT))
    if _TRUNCATION_NOTE_RE.match(text):
        return Finding("More findings of the same check were counted but not listed.")
    if lower.startswith("ruff:"):
        if _classify_issue(text).severity == "blocker":
            return Finding("The backend code uses a name that is undefined or defined twice, so it fails "
                           "when that code runs.")
        return Finding("The backend code has a lint finding.")
    if "but it doesn't exist" in lower:
        return Finding("A file the build refers to is missing.")
    for prefix, sentence in _SIMPLE:
        if lower.startswith(prefix):
            return Finding(sentence)
    return Finding(GENERIC_SENTENCE)


def user_sentence(message: str) -> str:
    """The sentence of :func:`user_finding`."""
    return user_finding(message).sentence


def agent_texts(messages: list[str]) -> dict[str, str]:
    """Each finding's user sentence (and a skipped check's plain name), mapped back to the
    text the agent reads: the message without its first prefix."""
    texts: dict[str, str] = {}
    for message in messages:
        texts.setdefault(user_sentence(message), message.partition(": ")[2] or message)
        if skipped := _DID_NOT_RUN.match(" ".join(message.split())):
            texts.setdefault(plain_check(skipped.group("check")), skipped.group("check"))
    return texts


# Above this many lines, findings of one group merge into one line.
GROUP_ABOVE = 5


def summary_lines(entries: list[tuple[Finding, str]], limit: int, quote=str) -> tuple[list[str], int]:
    """``(finding, line)`` pairs as at most ``limit`` lines, and how many findings they cover.

    ``quote`` renders a merged line as the given lines are rendered.

    Past ``GROUP_ABOVE`` lines, two or more findings of one group become one
    line, so a dozen untestable create routes do not hide everything else.
    """
    if len(entries) <= GROUP_ABOVE:
        shown = entries[:limit]
        return [line for _, line in shown], len(shown)
    members: dict[str, list[Finding]] = {}
    for finding, _ in entries:
        if finding.group in GROUP_SENTENCES:
            members.setdefault(finding.group, []).append(finding)
    lines: list[tuple[str, int]] = []
    done: set[str] = set()
    for finding, line in entries:
        group = members.get(finding.group, [])
        if len(group) < 2:
            lines.append((line, 1))
        elif finding.group not in done:
            done.add(finding.group)
            subjects = ", ".join(dict.fromkeys(f.subject for f in group if f.subject))
            lines.append((quote(GROUP_SENTENCES[finding.group].format(n=len(group), subjects=subjects)),
                          len(group)))
    shown = lines[:limit]
    return [line for line, _ in shown], sum(count for _, count in shown)
