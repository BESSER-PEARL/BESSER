# Characters ``str.splitlines`` breaks on besides ``\n``/``\r``. The tokenizer
# does not, but the B-UML importers split the source with ``splitlines()``
# before parsing, so a raw one cuts a literal (or a comment) in two.
_SPLITLINES_ONLY_BREAKS = '\x0b\x0c\x1c\x1d\x1e\x85  '
# ``\x00`` is refused by ``compile`` outright.
_LITERAL_ESCAPES = str.maketrans(
    {ch: f'\\u{ord(ch):04x}' for ch in _SPLITLINES_ONLY_BREAKS + '\x00'}
)
_COMMENT_BREAKS = str.maketrans({ch: ' ' for ch in _SPLITLINES_ONLY_BREAKS + '\n\r\x00'})


def _escape_python_string(value: str) -> str:
    """Escape a string for safe interpolation into generated Python source code.

    Prevents code injection when user-controlled values (names, labels, etc.)
    are embedded inside string literals in generated Python files that may
    later be executed with ``exec()``.
    """
    return (value
            .replace('\\', '\\\\')
            .replace("'", "\\'")
            .replace('"', '\\"')
            .replace('\n', '\\n')
            .replace('\r', '\\r')
            .translate(_LITERAL_ESCAPES))


def _comment_safe(name: str) -> str:
    """Sanitise a name for safe embedding in a ``#`` comment line.

    Replaces every line-breaking character (see ``_SPLITLINES_ONLY_BREAKS``)
    with a space so that a user-supplied name cannot break out of the comment
    into executable code when the generated source is later processed.
    """
    return (name or '').replace('\r\n', ' ').translate(_COMMENT_BREAKS)


def _sanitize_identifier(name: str) -> str:
    """Sanitize a string to be a valid Python identifier.

    Replaces any character other than ASCII letters, digits and ``_`` with
    ``_``, then strips leading characters that cannot start an identifier
    (digits, so ``1state`` becomes ``state``). Returns ``'unnamed'`` when
    nothing is left. Case is preserved and keywords are not suffixed — see
    :func:`safe_var_name` for that.
    """
    sanitized = re.sub(r'[^a-zA-Z0-9_]', '_', name)
    sanitized = re.sub(r'^[^a-zA-Z_]+', '', sanitized)
    return sanitized or 'unnamed'


def buml_header() -> str:
    """First line of a generated B-UML file: the BESSER version that wrote it."""
    return f"# Generated by BESSER {_comment_safe(get_besser_version())}\n"


def section_banner(keyword: str, title: Optional[str] = None) -> str:
    """The boxed ``# <KEYWORD> MODEL: "<title>" #`` banner that opens a model's section.

    ``project_to_json`` splits a project file on these lines and reads the
    title back as the diagram's title, so the title is made safe for that
    reader: one line (see :func:`_comment_safe`), and ``"`` becomes ``'``
    because the reader captures it as ``"([^"]*)"``.

    Args:
        keyword: The section keyword, e.g. ``"NN"`` or ``"KNOWLEDGE_GRAPH"``.
        title: The diagram title; without one the banner is ``# <KEYWORD> MODEL #``.

    Returns:
        str: The banner line between two ``#`` borders, newline-terminated.
    """
    if title:
        safe_title = _comment_safe(str(title)).replace('"', "'")
        header_line = f'# {keyword} MODEL: "{safe_title}" #'
    else:
        header_line = f"# {keyword} MODEL #"
    border = "#" * len(header_line)
    return f"{border}\n{header_line}\n{border}\n"


PRIMITIVE_TYPE_MAPPING = {
    'str': 'StringType',
    'string': 'StringType',
    'int': 'IntegerType',
    'integer': 'IntegerType',
    'float': 'FloatType',
    'bool': 'BooleanType',
    'boolean': 'BooleanType',
    'time': 'TimeType',
    'date': 'DateType',
    'datetime': 'DateTimeType',
    'timedelta': 'TimeDeltaType',
    'any': 'AnyType'
}

# Names a generated structural script imports (plus ``datetime``, which rebuilds
# element timestamps and object slot values). A class or enumeration variable
# with one of these names would shadow the import, so it gets a suffix.
RESERVED_NAMES = [
    'Class', 'Property', 'Method', 'Parameter',
    'BinaryAssociation', 'Generalization', 'DomainModel',
    'Enumeration', 'EnumerationLiteral', 'Multiplicity',
    'StringType', 'IntegerType', 'FloatType', 'BooleanType',
    'TimeType', 'DateType', 'DateTimeType', 'TimeDeltaType',
    'AnyType', 'Constraint', 'AssociationClass', 'Metadata', 'MethodImplementationType',
    'ObjectModel', 'datetime',
]


def timestamp_expr(element: Any) -> Optional[str]:
    """Return Python source rebuilding ``element.timestamp``, or ``None``.

    Only an explicit timestamp is emitted (passed to the constructor, set
    later, or read from editor JSON); one that defaulted to the creation time
    gives ``None``, so building the same model always yields the same source.
    The generated file must ``import datetime``.
    """
    iso = explicit_timestamp_iso(element)
    if iso is None:
        return None
    return f'datetime.datetime.fromisoformat("{_escape_python_string(iso)}")'


def timestamp_kwarg(element: Any) -> str:
    """Return a ``, timestamp=...`` constructor argument for ``element``.

    Empty string when the element has no timestamp (see :func:`timestamp_expr`).
    """
    expr = timestamp_expr(element)
    return f", timestamp={expr}" if expr else ""


def id_kwarg(element: Any, emit_ids: bool) -> str:
    """Return a ``, id="..."`` constructor argument for ``element``.

    Empty string when ``emit_ids`` is false or the element has no id, so the
    source is then the same as before ids existed.
    """
    if not emit_ids:
        return ""
    element_id = getattr(element, "id", None)
    if not isinstance(element_id, str) or not element_id:
        return ""
    return f', id="{_escape_python_string(element_id)}"'


def safe_var_name(name: str, lowercase: bool = True) -> str:
    """
    Convert a name to a safe Python variable name.

    By default the result is lowercased — this is the historical behavior
    relied on by ``agent_model_builder`` and by ``WebAppGenerator``'s
    ``agent_slug`` (filesystem paths, container names, and hostnames are
    conventionally lowercase). Callers that need to preserve the user's
    original casing — e.g. emitting Python identifiers that must round-trip
    unchanged — can opt in via ``lowercase=False``.

    Args:
        name: Original name
        lowercase: If True (default), lowercase the result.

    Returns:
        Safe variable name
    """
    return sanitize_identifier(
        name,
        collapse_underscores=True,
        strip_underscores=True,
        lowercase=lowercase,
        empty="unnamed",
        # Only names that are *actually* reserved Python keywords are escaped.
        # Python keywords are all lowercase (``class``, ``from``, ``return``, ...),
        # so a PascalCase identifier like ``Class`` is a perfectly valid attribute
        # or variable name and round-trips unchanged when ``lowercase=False``.
        escape_keywords=True,
    )


def identifier_part(name: str) -> str:
    """Return ``name`` when it is a valid identifier, else a sanitised one.

    ``NamedElement.name`` only rejects spaces and hyphens, so a name can hold
    ``;``, ``(`` or a newline. Writing such a name as a variable would let it
    escape into executable code when the generated file runs. A valid name is
    kept unchanged, so ordinary models generate the same code as before; any
    other name gets its invalid characters replaced and a short hash of the
    original appended, so two different names never map to the same variable.
    """
    if name.isidentifier():
        return name
    digest = hashlib.sha1(name.encode('utf-8')).hexdigest()[:6]
    return f"{_sanitize_identifier(name)}_{digest}"


def safe_class_name(name):
    """
    Add a suffix to class names that match reserved keywords or BUML metaclass names.
    If the name already ends with an underscore and would conflict with a reserved name,
    add a numeric suffix instead.

    Parameters:
    name (str): The original class name

    Returns:
    str: A safe variable name for the class
    """
    if not name:
        return "unnamed_class"

    name = identifier_part(name)
    if keyword.iskeyword(name):
        return f"{name}_"
    if name.endswith('_'):
        base_name = name[:-1]
        if base_name in RESERVED_NAMES:
            return f"{name}var"
        return name
    elif name in RESERVED_NAMES:
        return f"{name}_"
    else:
        return name


def attribute_var_name(class_name: str, attribute_name: str) -> str:
    """Variable the domain builder binds an attribute to: ``<Class>_<attribute>``.

    Other builders and converters that refer to an attribute variable (GUI
    table columns, the GUI converter's namespace) must use this helper too.
    """
    return f"{safe_class_name(class_name)}_{identifier_part(attribute_name)}"


def method_var_name(class_name: str, method_name: str) -> str:
    """Variable the domain builder binds a method to: ``<Class>_m_<method>``.

    ``method_name`` may carry a signature (``total(x: int)``); only the part
    before ``(`` is used.
    """
    base = method_name.split('(')[0] if '(' in method_name else method_name
    return f"{safe_class_name(class_name)}_m_{safe_var_name(base, lowercase=False)}"


class NameDispenser:
    """Mint one unique Python variable name per metamodel object.

    Element names can be empty, repeated, or contain spaces, so identity is by
    object: the name combines the lowercased metamodel class name with a
    sanitised ``obj.name`` and a numeric suffix when needed, and is cached so
    every later reference (relationship endpoints, containment calls) resolves
    to the same identifier. ``reserve`` blocks names the caller already uses,
    such as the model variable itself.

    ``type_prefix=False`` drops the metamodel-class prefix and
    ``lowercase=False`` keeps the user's casing, for scripts whose variables
    should read like the element names (the domain model builder).
    """

    def __init__(self, reserved: Iterable[str] = (), *, type_prefix: bool = True,
                 lowercase: bool = True):
        self._used: set = set(reserved)
        self._for_obj: dict = {}
        self._type_prefix = type_prefix
        self._lowercase = lowercase

    def reserve(self, name: str) -> None:
        """Mark ``name`` as taken so no element is given it."""
        self._used.add(name)

    def name_for(self, obj) -> str:
        """Return the variable name for ``obj``, minting it on first use."""
        if obj in self._for_obj:
            return self._for_obj[obj]
        base = safe_var_name(obj.name, lowercase=self._lowercase)
        if self._type_prefix:
            prefix = type(obj).__name__.lower()
            stem = f"{prefix}_{base}"
            candidate = prefix if base == prefix else stem
        else:
            stem = candidate = base
        suffix = 1
        while candidate in self._used:
            candidate = f"{stem}_{suffix}"
            suffix += 1
        self._used.add(candidate)
        self._for_obj[obj] = candidate
        return candidate


def emit_layout_line(var_name: str, layout: Optional[dict]) -> Optional[str]:
    """Return ``<var>.layout = {...}``, or ``None`` when there is no layout.

    Layouts are opaque diagram-interchange dicts of primitives stashed by the
    JSON converters; ``repr`` emits them as valid Python literals.
    """
    if not layout:
        return None
    return f"{var_name}.layout = {layout!r}"


def bind_domain_field(domain_model: Optional["DomainModel"], class_name: str,
                      field_name: str) -> Optional["Property"]:
    """Return the ``Property`` named *field_name* on *class_name*, or ``None``.

    Emitted GUI code calls this instead of inlining the lookup: the inline form
    used ``globals().get(...)``, an ``if``, a generator expression and
    ``_``-prefixed names, all refused by the safe BUML loader, so a domain-bound
    DataBinding could be exported and never re-imported.

    Returns ``None`` rather than raising when the model, class or field is
    absent - a GUI model is often exported without its domain model, so the
    binding degrades to "unbound" instead of breaking the import.
    """
    owner = _resolve_domain_class(domain_model, class_name)
    if owner is None:
        return None
    for attribute in getattr(owner, "attributes", ()) or ():
        if getattr(attribute, "name", None) == field_name:
            return attribute
    return None


def _resolve_domain_class(domain_model: Optional["DomainModel"], class_name: str) -> Optional["Class"]:
    """Return the class named *class_name* in *domain_model*, or ``None``."""
    if domain_model is None:
        return None
    try:
        return domain_model.get_class_by_name(class_name)
    except Exception:
        return None


def build_data_binding(domain_model: Optional["DomainModel"], class_name: str, label_field: Optional[str] = None,
                       data_field: Optional[str] = None, **kwargs: Any) -> Optional["DataBinding"]:
    """Return a ``DataBinding`` over *class_name*, or ``None`` if the class is absent.

    Emitted GUI code calls this for the same reason as ``bind_domain_field``: the
    inline form needed ``globals()``, an ``if`` and generator expressions, which
    the safe BUML loader refuses. *label_field* / *data_field* are attribute
    names; the other keyword arguments go to the ``DataBinding`` constructor.
    """
    from besser.BUML.metamodel.gui.binding import DataBinding

    owner = _resolve_domain_class(domain_model, class_name)
    if not owner:
        return None
    binding = DataBinding(domain_concept=owner, **kwargs)
    if label_field:
        binding.label_field = bind_domain_field(domain_model, class_name, label_field)
    if data_field:
        binding.data_field = bind_domain_field(domain_model, class_name, data_field)
    return binding


def bind_association_end(domain_model: Optional["DomainModel"], end_name: str) -> Optional["Property"]:
    """Return the association end named *end_name*, or ``None``.

    A table's lookup column refers to an end that only exists inside its
    ``BinaryAssociation``; the inline ``next(...)`` lookup emitted before was
    refused by the safe BUML loader, so a project with such a table could be
    exported but never re-imported.
    """
    for association in getattr(domain_model, "associations", ()) or ():
        for end in association.ends:
            if end.name == end_name:
                return end
    return None


def bind_data_source(source: "DataSourceElement", domain_model: Optional["DomainModel"], class_name: str,
                     field_names: Optional[Iterable[str]] = None, label_field: Optional[str] = None,
                     value_field: Optional[str] = None) -> None:
    """Bind a ``DataSourceElement`` to *class_name* when the domain model has it.

    The emitted code sets the unresolved names (``field_names``,
    ``label_field_name``, ``value_field_name``) before calling this, so a model
    loaded without its domain model keeps them; this only adds the resolved
    class and properties, in the order the former inline code used.
    """
    owner = _resolve_domain_class(domain_model, class_name)
    if not owner:
        return
    source.dataSourceClass = owner
    if field_names:
        source.fields = {attr for attr in owner.attributes if attr.name in field_names}
        # After ``fields``: its setter rewrites field_names in set order.
        source.field_names = list(field_names)
    if label_field:
        source.label_field = bind_domain_field(domain_model, class_name, label_field)
        source.label_field_name = label_field
    if value_field:
        source.value_field = bind_domain_field(domain_model, class_name, value_field)
        source.value_field_name = value_field
