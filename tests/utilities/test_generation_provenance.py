class TestGeneratedZip:
    def test_zip_has_provenance_file_with_version_generator_and_options(self):
        response = _generate("django", {
            "project_name": "library_site", "app_name": "books", "containerization": False,
            "api_key": "sk-NEVER-LEAK-123", "github_token": "ghp_NEVER_LEAK",
        })
        entries = _zip_entries(response.content)
        assert PROVENANCE_FILENAME in entries
        text = entries[PROVENANCE_FILENAME].decode("utf-8")
        assert f"BESSER version: `{VERSION}`" in text
        assert "Generator: `django`" in text
        assert "project_name: `library_site`" in text
        assert "app_name: `books`" in text
        assert "https://github.com/BESSER-PEARL/BESSER" in text
        assert "overwrites" in text
        assert "NEVER" not in text and "api_key" not in text and "token" not in text

    def test_standard_zip_generator_has_provenance_file(self):
        entries = _zip_entries(_generate("java").content)
        assert "Generator: `java`" in entries[PROVENANCE_FILENAME].decode("utf-8")

    def test_two_generations_are_identical_including_the_provenance_file(self):
        first = _zip_entries(_generate("backend").content)
        second = _zip_entries(_generate("backend").content)
        assert PROVENANCE_FILENAME in first
        assert first == second

    def test_provenance_entry_itself_is_byte_identical(self):
        def entry_info(content):
            with zipfile.ZipFile(io.BytesIO(content)) as archive:
                info = archive.getinfo(PROVENANCE_FILENAME)
                return info.date_time, info.CRC, archive.read(PROVENANCE_FILENAME)
        assert entry_info(_generate("java").content) == entry_info(_generate("java").content)

    def test_agent_zip_gets_provenance_file(self):
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w") as archive:
            archive.writestr("agent.py", "print('hi')\n")
        _streaming_zip(buffer, "agent_output.zip")
        entries = _zip_entries(buffer.getvalue())
        assert set(entries) == {"agent.py", PROVENANCE_FILENAME}
        assert "Generator: `agent`" in entries[PROVENANCE_FILENAME].decode("utf-8")


class TestSingleFile:
    def test_python_file_starts_with_version_comment_and_parses(self):
        body = _generate("python").text
        assert body.startswith(HEADER)
        ast.parse(body)

    def test_sql_file_starts_with_version_comment_and_runs(self):
        body = _generate("sql", {"dialect": "sqlite"}).text
        assert body.startswith(f"-- Generated by BESSER {VERSION}\n")
        with sqlite3.connect(":memory:") as connection:
            connection.executescript(body)

    def test_json_file_is_left_unchanged(self):
        body = _generate("jsonschema").text
        assert "Generated by BESSER" not in body
        json.loads(body)


class TestBumlExport:
    def test_domain_model_file_starts_with_version_and_round_trips(self, tmp_path):
        path = tmp_path / "model.py"
        domain_model_to_code(process_class_diagram({"title": "Library", "model": CLASS_MODEL}), str(path))
        code = path.read_text(encoding="utf-8")
        assert code.startswith(HEADER)
        parsed = parse_buml_content(code)
        assert {c.name for c in parsed.get_classes()} == {"Author", "Book"}

    def test_project_file_has_one_version_header_and_round_trips(self, tmp_path):
        domain = process_class_diagram({"title": "Library", "model": CLASS_MODEL})
        path = tmp_path / "project.py"
        project_to_code(Project(
            name="LibraryProject", models=[domain], owner="me", metadata=Metadata(description="d"),
        ), str(path))
        code = path.read_text(encoding="utf-8")
        assert code.startswith(HEADER)
        assert code.count("Generated by BESSER") == 1
        diagrams = project_to_json(code)["diagrams"]["ClassDiagram"]
        names = {e["name"] for e in diagrams[0]["model"]["elements"].values() if e["type"] == "Class"}
        assert names == {"Author", "Book"}


class TestSpecDriven:
    def _package(self, tmp_path, files):
        result_path = tmp_path / "result"
        result_path.mkdir()
        for name, text in files.items():
            (result_path / name).write_text(text, encoding="utf-8")
        (result_path / ".besser_recipe.json").write_text(
            json.dumps({"generator_used": "backend", "llm_model": "claude-sonnet-4-5"}), encoding="utf-8"
        )
        runner = SmartGenerationRunner(_build_request())
        runner.temp_dir = str(tmp_path)
        return result_path, runner._package_result(str(result_path))

    def test_recipe_records_the_besser_version(self, tmp_path):
        result_path, (done, _) = self._package(tmp_path, {"main.py": "x = 1\n", "app.py": "y = 2\n"})
        assert done.recipe["besser_version"] == VERSION
        on_disk = json.loads((result_path / ".besser_recipe.json").read_text(encoding="utf-8"))
        assert on_disk["besser_version"] == VERSION

    def test_zip_download_carries_provenance_file(self, tmp_path):
        _, (done, entry) = self._package(tmp_path, {"main.py": "x = 1\n", "app.py": "y = 2\n"})
        text = _zip_entries(open(entry.file_path, "rb").read())[PROVENANCE_FILENAME].decode("utf-8")
        assert f"BESSER version: `{VERSION}`" in text
        assert "Generator: `spec_driven_agent`" in text
        assert "base_generator: `backend`" in text
        assert "NEVER-LEAK" not in text
        assert done.fileCount == 2

    def test_single_file_run_stays_a_single_file_but_the_workspace_has_provenance(self, tmp_path):
        result_path, (done, entry) = self._package(tmp_path, {"main.py": "x = 1\n"})
        assert entry.is_zip is False and entry.file_name == "main.py"
        # The GitHub push copies the workspace, so the file travels there.
        assert (result_path / PROVENANCE_FILENAME).is_file()


