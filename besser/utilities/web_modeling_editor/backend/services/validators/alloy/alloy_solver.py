import os
import tempfile
from besser.BUML.metamodel.object import ObjectModel
from besser.BUML.metamodel.project import Project
from besser.BUML.metamodel.structural import DomainModel, Metadata
from besser.generators.alloy.alloy_generator import AlloyGenerator
from besser.generators.alloy.alloy_specification import AlloyBounds, AlloySpecification
from besser.utilities.buml_code_builder.project_builder import project_to_code
from besser.utilities.web_modeling_editor.backend.services.validators.alloy.alloy_analyzer_executor import (
    AlloyAnalyzerExecutor,
    AlloyResult,
)
from besser.utilities.web_modeling_editor.backend.services.validators.alloy.alloy_instance_to_object_model import (
    AlloyInstanceToObjectModel,
)

# Seconds the Alloy Analyzer may run before an analysis times out.
_DEFAULT_TIMEOUT_SECONDS = 30

class AlloySolver:
    """Performs different kinds of automated analyses on B-UML models annotated with OCL invariants.
    It can check for model consistency (i.e., satisfiability) and generate object diagrams for the model.
    It employs the Alloy Analyzer as a backend for analysis.

    Each analysis runs on the Alloy specification of its scope and seed, generated with
    :class:`AlloyGenerator` on demand, or reused when it is the one last generated;
    :meth:`generate_specification` gives what a scope searches before analyzing it. The solver
    assumes its model does not change between calls, as a reused specification would be stale.
    When *output_dir* is ``None``, the specification and the Alloy Analyzer's output are written to
    a temporary directory owned by the solver.
    """

    def __init__(self, model: DomainModel, output_dir: str | None = None):
        if output_dir is None:
            self._temp_dir = tempfile.TemporaryDirectory(prefix="besser_alloy_")
            output_dir = self._temp_dir.name
        self.model = model
        self.output_dir = output_dir
        self.alloy_output_dir = os.path.join(self.output_dir, "alloy_output")
        self.generator = AlloyGenerator(model=self.model, output_dir=self.output_dir)
        self.executor = AlloyAnalyzerExecutor()
        # The specification last generated, and its (scope, seed); None before the first one
        self.specification: AlloySpecification | None = None
        self._specification_key: tuple[int, int] | None = None

    def get_scopes(self) -> AlloyBounds | None:
        """Returns what the specification last generated (by :meth:`generate_specification` or an
        analysis) searches, ``None`` before any."""
        return self.specification.get_scopes() if self.specification else None

    def generate_specification(self, scope: int = 5, seed: int = 0) -> AlloyBounds:
        """Writes the Alloy specification of the model for *scope*, unless it is the one last written,
        without analyzing it; returns what an analysis of it searches.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            seed: the seed of the random literals generated by the translator.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        if self._specification_key != (scope, seed):
            self.generator.generate(scope, seed)
            self.specification = self.generator.specification_model
            self.specification_path = self.generator.get_specification_path()
            self._specification_key = (scope, seed)
        return self.specification.get_scopes()

    def check_consistency(self, scope: int = 5, seed: int = 0, timeout: int = _DEFAULT_TIMEOUT_SECONDS) -> AlloyResult:
        """Execute the Alloy Analyzer and check model satisfiability.
        Returns an AlloyResult indicating whether the model is satisfiable
        (SAT), unsatisfiable (UNSAT), if the analysis timed out (TIMEOUT), if the bounds
        of *scope* are too large for the Alloy Analyzer (SCOPES_TOO_LARGE), or if the
        Alloy Analyzer failed for any other reason (ERROR).

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            seed: the seed of the random literals generated by the translator.
            timeout: seconds the Alloy Analyzer may run before the analysis times out.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        self.generate_specification(scope, seed)
        result, _ = self.executor.generate_instances(
            self.specification_path, self.alloy_output_dir, timeout=timeout
        )
        return result

    def generate_object_models(
        self, scope: int = 5, num_models: int = 1, seed: int = 0, timeout: int = _DEFAULT_TIMEOUT_SECONDS
    ) -> tuple[AlloyResult, list[ObjectModel]]:
        """Generates B-UML object models of the model using Alloy.
        Returns an AlloyResult indicating the result of the analysis (see :meth:`check_consistency`)
        and a list with an object model per satisfying instance found. The list is empty unless
        the result is SAT.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            num_models: Number of satisfying instances to request from the Alloy
                Analyzer.
            seed: The seed of the random literals generated by the translator.
            timeout: seconds the Alloy Analyzer may run before the analysis times out.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        self.generate_specification(scope, seed)
        (result, instance_xml_files) = self.executor.generate_instances(
            self.specification_path, self.alloy_output_dir, num_instances=num_models, timeout=timeout
        )
        if result != AlloyResult.SAT:
            return result, []
        converter = AlloyInstanceToObjectModel(self.model, self.specification)
        object_models = [
            converter.convert(xml_file, name=f"Object_Diagram_{i}")
            for i, xml_file in enumerate(instance_xml_files)
        ]
        return result, object_models

    def generate_project(
        self, scope: int = 5, num_models: int = 1, seed: int = 0, timeout: int = _DEFAULT_TIMEOUT_SECONDS
    ) -> tuple[AlloyResult, Project | None]:
        """Generates a B-UML project with the model and object models of it generated using Alloy.
        Returns an AlloyResult indicating the result of the analysis (see :meth:`check_consistency`)
        and the project, whose models are the domain model followed by an object model per
        satisfying instance found. The project is ``None`` unless the result is SAT.

        The project can be written with :meth:`generate_project_file`, producing a file that
        can be imported into the web modeling editor.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            num_models: Number of satisfying instances to request from the Alloy
                Analyzer.
            seed: The seed of the random literals generated by the translator.
            timeout: seconds the Alloy Analyzer may run before the analysis times out.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        result, object_models = self.generate_object_models(
            scope=scope, num_models=num_models, seed=seed, timeout=timeout
        )
        if result != AlloyResult.SAT:
            return result, None
        metadata = Metadata(description=f"Model {self.model.name} and object models of it generated with Alloy")
        return result, Project(name="Alloy_project", models=[self.model, *object_models], metadata=metadata)

    def generate_project_file(
        self, scope: int = 5, num_models: int = 1, seed: int = 0, timeout: int = _DEFAULT_TIMEOUT_SECONDS
    ) -> AlloyResult:
        """Generates a B-UML project with the model and object models of it generated using Alloy
        (see :meth:`generate_project`), and writes its B-UML code to ``alloy_project.py`` in the
        output directory. Returns an AlloyResult indicating the result of the analysis (see
        :meth:`check_consistency`). The file is written only if the result is SAT; it can be imported into the web
        modeling editor. When the solver was created without *output_dir*, the file is written to
        the solver's temporary directory, which is deleted with the solver.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            num_models: Number of satisfying instances to request from the Alloy
                Analyzer.
            seed: The seed of the random literals generated by the translator.
            timeout: seconds the Alloy Analyzer may run before the analysis times out.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        result, project = self.generate_project(scope=scope, num_models=num_models, seed=seed, timeout=timeout)
        if result == AlloyResult.SAT:
            project_to_code(project, os.path.join(self.output_dir, "alloy_project.py"))
        return result
