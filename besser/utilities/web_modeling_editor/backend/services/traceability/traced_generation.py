"""Code generation that also returns the trace of the run.

A traced generation runs the request through the same dispatch as ``/generate-output``
and ``/generate-output-from-project`` (``services/generation``), so it accepts every
generator they accept and delivers the same bytes: a single file with the same name
and ``Generated by BESSER`` header, or the same ZIP with its ``BESSER_GENERATION.md``.
The trace is built from that delivery: every text file it holds is linked from every
diagram the run read, and the files the generator recorded traces for (instrumented
generators, see ``GeneratorInterface.traced_files``) get their line ranges too. Its
paths and line numbers refer to the delivery.
"""

import asyncio
import base64
import io
import zipfile
from datetime import datetime, timezone
from typing import Awaitable, Callable, Dict, List, Sequence

from besser.utilities.generation_trace import (
    ElementRef, GeneratedFile, InputModel, build_generation_trace, generated_text_files, input_model,
)
from besser.utilities.provenance import PROVENANCE_FILENAME, get_besser_version
from besser.utilities.web_modeling_editor.backend.constants.constants import TRACE_MAX_STORED_CONTENT_BYTES
from besser.utilities.web_modeling_editor.backend.models import DiagramInput, ProjectInput
from besser.utilities.web_modeling_editor.backend.models.traceability import (
    TracedGenerationInput,
    TracedGenerationResponse,
    TracedProjectGenerationInput,
)
from besser.utilities.web_modeling_editor.backend.services.converters import trace_buml_to_json
from besser.utilities.web_modeling_editor.backend.services.exceptions import ValidationError
from besser.utilities.web_modeling_editor.backend.services.generation import (
    DiagramRead,
    GeneratedOutput,
    Generation,
    generate_from_diagram,
    generate_from_project,
)


async def generate_with_trace(input_data: TracedGenerationInput) -> TracedGenerationResponse:
    """Run ``/generate-output`` on one diagram and return its delivery with the trace fragment of the run.

    Raises:
        ValidationError: If the diagram has no id, or the generator or diagram is refused as by
            ``/generate-output``.
        ConversionError: If the diagram cannot be converted to B-UML.
    """
    if not input_data.id:
        raise ValidationError("A traced generation needs the diagram id: the trace refers to the model by it.")
    diagram = DiagramInput.model_validate(input_data.model_dump(exclude={"actorName"}))
    return await _traced(lambda: generate_from_diagram(diagram), input_data.generator, input_data.actorName)


async def generate_project_with_trace(input_data: TracedProjectGenerationInput) -> TracedGenerationResponse:
    """Run ``/generate-output-from-project`` and return its delivery with the trace fragment of the run.

    Raises:
        ValidationError: If a diagram the generator reads has no id, or the request is refused as by
            ``/generate-output-from-project``.
        ConversionError: If a diagram cannot be converted to B-UML.
    """
    project = ProjectInput.model_validate(input_data.model_dump(exclude={"actorName"}))
    generator = (project.settings or {}).get("generator")
    return await _traced(lambda: generate_from_project(project), generator, input_data.actorName)


async def _traced(generate: Callable[[], Awaitable[Generation]], generator: str,
                  actor_name: str) -> TracedGenerationResponse:
    """Run ``generate`` and return what it delivered with the trace fragment of the run."""
    started_at = datetime.now(timezone.utc)
    generation = await generate()
    ended_at = datetime.now(timezone.utc)
    models = _input_models(generation.diagrams)
    delivered = _delivered_bytes(generation.output)
    trace = await asyncio.to_thread(
        _trace_json, generation.output, delivered, models, generator, actor_name, started_at, ended_at)
    return TracedGenerationResponse(
        fileName=generation.output.file_name,
        mediaType=generation.output.media_type,
        contentBase64=base64.b64encode(delivered).decode("ascii"),
        trace=trace,
    )


def _input_models(diagrams: Sequence[DiagramRead]) -> List[InputModel]:
    """The models of a trace, one per diagram read.

    Raises:
        ValidationError: If a diagram has no id.
    """
    missing = [read.title for read in diagrams if not read.diagram_id]
    if missing:
        raise ValidationError("A traced generation needs the id of every diagram it reads: the trace refers to "
                              f"each model by it. Without an id: {', '.join(missing)}.")
    return [input_model(read.model, read.diagram_id, read.title) if read.model is not None
            else InputModel(ElementRef(read.diagram_id, read.metaclass, read.title)) for read in diagrams]


def _delivered_bytes(output: GeneratedOutput) -> bytes:
    return output.content.getvalue() if output.is_zip else output.content


def _delivered_files(output: GeneratedOutput, delivered: bytes) -> List[GeneratedFile]:
    """The text files of the delivery, with what they were rendered from. The provenance note a
    ZIP carries is added by the delivery, not generated, so it is left out."""
    if not output.is_zip:
        return generated_text_files([(output.file_name, delivered)], output.traced_files)
    with zipfile.ZipFile(io.BytesIO(delivered)) as archive:
        entries = [(info.filename, archive.read(info)) for info in archive.infolist()
                   if not info.is_dir() and info.filename != PROVENANCE_FILENAME]
    return generated_text_files(entries, output.traced_files)


def _trace_json(output: GeneratedOutput, delivered: bytes, models: List[InputModel], generator: str,
                actor_name: str, started_at: datetime, ended_at: datetime) -> Dict:
    trace = build_generation_trace(
        _delivered_files(output, delivered),
        models=models,
        generator=generator,
        generator_version=get_besser_version(),
        actor_name=actor_name,
        max_stored_content_bytes=TRACE_MAX_STORED_CONTENT_BYTES,
        started_at=started_at,
        ended_at=ended_at,
        ai_files=output.ai_files,
        llm=output.ai_llm,
    )
    return trace_buml_to_json(trace)
