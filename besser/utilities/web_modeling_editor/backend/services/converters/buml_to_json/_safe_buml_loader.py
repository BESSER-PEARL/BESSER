"""
Safe AST-based loader for BUML Python files uploaded by users.

BUML files generated by our code builders are simple: a sequence of top-level
assignments and method calls that construct BUML metamodel instances via their
public constructors. Top-level imports are skipped, never executed (an
``X as Y`` alias of an allowed name binds ``Y`` to it); there are no
function/class definitions, no control flow, no comprehensions.

Files written by hand or by an LLM are runnable scripts: helper functions that
build the model, a validation check that prints, a generator run, an
``if __name__ == "__main__":`` block. When the caller collects ``warnings``
(a model a user uploads), plain top-level functions are accepted, their bodies
validated like the rest, the main block is loaded like top-level code, and a
statement that runs the script rather than building the model (it uses a name
that is not B-UML, such as ``print`` or a generator) is skipped, never run, and
reported there.

This loader validates the AST against a strict allowlist of node types and
name references BEFORE executing it. Anything outside the allowlist raises
``SafeBumlLoaderError``. Only after validation passes do we compile and
``exec()`` the tree, with ``__builtins__`` zeroed out so attribute access on
primitives cannot reach dangerous helpers either.

This replaces the previous ``exec(cleaned_content, safe_globals, local_vars)``
pattern, which was bypassable via ``__class__.__mro__`` introspection on any
value inside ``safe_globals``.
"""
from __future__ import annotations

import ast
import datetime as _datetime
import logging
import sys
import types
from typing import Any, Dict, Mapping, Optional, Set

logger = logging.getLogger(__name__)


# Stand-in for the ``datetime`` module, for ``allowed_names``. Generated BUML
# rebuilds element timestamps (and object slot values) with
# ``datetime.datetime.fromisoformat("...")`` after an ``import datetime`` that
# the caller strips. Only the ``datetime`` class is exposed, not the module.
#
# Callers put this sentinel in ``allowed_names``; ``safe_load_buml`` swaps it
# for a fresh namespace from ``make_safe_datetime_module()`` on every call, so
# the object an upload actually sees is never shared with another upload.
SAFE_DATETIME_MODULE = types.SimpleNamespace(datetime=_datetime.datetime)


def make_safe_datetime_module() -> types.SimpleNamespace:
    """Return a new, per-load stand-in for the ``datetime`` module."""
    return types.SimpleNamespace(datetime=_datetime.datetime)


class SafeBumlLoaderError(ValueError):
    """Raised when the BUML content contains disallowed constructs."""


# Resource limits. Real BUML files from our code builder are ~a few KB with
# a few hundred AST nodes at most. These caps are defence-in-depth against
# accidentally-huge or maliciously-crafted uploads (e.g. a 50 MB file of
# nested list literals that would blow up the recursive validator).
_MAX_CONTENT_BYTES = 1_000_000         # 1 MB source limit
_MAX_AST_NODES = 20_000                # total nodes after ``ast.parse``
_MAX_AST_DEPTH = 80                    # recursion depth for validator walk


# AST node types we accept. Anything not in this set is rejected.
#
# Rationale: these are the minimum nodes required to represent BUML files
# produced by besser.utilities.buml_code_builder: top-level assignments,
# constructor calls, literals, containers (list/tuple/set/dict), attribute
# chains for ``x.items.add(...)`` patterns, negative numeric literals, simple
# ``"a" + "b"`` string concatenation for composed names, and subscripting for
# indexing into dicts or lists.
_ALLOWED_NODE_TYPES: Set[type] = {
    ast.Module,
    ast.Expr,
    ast.Assign,
    # ``AnnAssign`` covers annotated assignments like ``x: Property = ...`` —
    # our code builder emits these heavily for readability. The annotation
    # itself is just a Name/Attribute that gets validated like any other
    # reference; the value side is the actual side-effecting part and is
    # validated normally.
    ast.AnnAssign,
    ast.Call,
    ast.Name,
    ast.Attribute,
    ast.Constant,
    ast.List,
    ast.Tuple,
    ast.Set,
    ast.Dict,
    ast.keyword,
    ast.BinOp,
    ast.UnaryOp,
    ast.Subscript,
    ast.Load,
    ast.Store,
    # Operator node classes that appear as children of BinOp / UnaryOp.
    # The actual *operator* is validated separately (only Add for BinOp,
    # USub/UAdd/Not for UnaryOp) via the _ALLOWED_BINOPS and
    # _ALLOWED_UNARY_OPS checks below. We have to list every operator class
    # we accept here because AST traversal visits the operator node too.
    ast.Add,
    ast.BitOr,
    ast.USub,
    ast.UAdd,
    ast.Not,
    # ``try: <assignments> except NameError: pass`` — the ONE control-flow shape
    # our own builders emit, around a method's ``state_machine`` /
    # ``quantum_circuit`` assignment (``sm`` / ``qc`` exists only in a project
    # export). Without these three types the loader rejected files BESSER itself
    # had just written. It adds branching, not reach: the body is
    # validated like any other statement, and _validate_try_shape below pins the
    # handler to ``except NameError: pass``.
    ast.Try,
    ast.ExceptHandler,
    ast.Pass,
    # ``return`` inside a top-level helper function (validated by
    # _validate_function); at module level Python itself refuses it.
    ast.Return,
}

# Statements allowed at module level. A ``FunctionDef`` is a plain helper,
# checked by _validate_function, and only in a hand-written script (``warnings``).
_TOP_LEVEL_STATEMENTS = (ast.Assign, ast.AnnAssign, ast.Expr, ast.Try, ast.FunctionDef)

# How a refused top-level statement is named in the error.
_STATEMENT_NAMES = {
    "For": "a for loop", "AsyncFor": "a for loop", "While": "a while loop",
    "If": "an if statement", "With": "a with block", "AsyncWith": "a with block",
    "ClassDef": "a class definition", "AsyncFunctionDef": "an async function",
    "Delete": "a del statement", "AugAssign": "an augmented assignment (+=)",
    "Global": "a global statement", "Raise": "a raise statement", "Assert": "an assert",
    "FunctionDef": "a function definition",
}

# Calls of the file's own functions, per load. A builder calls a helper once per
# element (tens of calls); without a cap, helpers that each call the one below
# twice reach 2**n calls from a few lines.
_MAX_FUNCTION_CALLS = 10_000
_CALL_COUNTER_NAME = "_besser_count_call"

# Inside ``UnaryOp`` we only allow the operators needed for signed numeric
# literals (``-1``, ``+1``) and the occasional boolean negation flag.
_ALLOWED_UNARY_OPS: Set[type] = {ast.USub, ast.UAdd, ast.Not}

# Resolvable in the sandbox only so `except NameError:` works.
_EXCEPTION_NAMES: Set[str] = {"NameError"}

# ``BinOp`` is limited to addition (identifier parts, ``prefix + name``) and
# ``|`` (set union, ``types={...} | {...}``). The only metamodel ``__or__``
# builds a BAL ``TypeUnion``. All other binary operators are rejected.
_ALLOWED_BINOPS: Set[type] = {ast.Add, ast.BitOr}


# String formatting resolves attribute and index lookups from inside the
# format string, which the AST walk cannot inspect; ``mro`` exposes the class
# hierarchy. The property accessors (``PrimitiveDataType.name.fset``) write
# to any object, bypassing the attribute-write guard, and ``type_mapping`` is
# a class-level dict shared by the whole process. No BUML file needs any of them.
_FORBIDDEN_ATTRIBUTES: Set[str] = {
    "format", "format_map", "mro",
    "fget", "fset", "fdel", "getter", "setter", "deleter",
    "type_mapping",
}


def _is_dunder(name: str) -> bool:
    """Return True for names starting with ``_`` (includes dunders)."""
    return name.startswith("_")



def _validate_try_shape(node: ast.Try) -> None:
    """Permit only ``try: ... except NameError: pass``.

    Anything else — a bare ``except``, a different exception, a handler with a
    real body, ``else``/``finally`` — is refused. The handler is the part an
    attacker would want (it runs on failure and is easy to overlook), so it is
    pinned to a literal ``pass`` rather than validated like ordinary code.
    """
    if node.orelse or node.finalbody:
        raise SafeBumlLoaderError(
            "try/except with else or finally is not allowed in BUML"
        )
    if not node.handlers:
        raise SafeBumlLoaderError("try without except is not allowed in BUML")
    for handler in node.handlers:
        if handler.type is None:
            raise SafeBumlLoaderError("bare except is not allowed in BUML")
        if not (isinstance(handler.type, ast.Name) and handler.type.id == "NameError"):
            raise SafeBumlLoaderError(
                "only 'except NameError' is allowed in BUML"
            )
        if handler.name is not None:
            raise SafeBumlLoaderError("'except NameError as e' is not allowed in BUML")
        if len(handler.body) != 1 or not isinstance(handler.body[0], ast.Pass):
            raise SafeBumlLoaderError(
                "the NameError handler must contain exactly 'pass'"
            )

def _attribute_root_name(node: ast.AST) -> str | None:
    """
    Walk an ``Attribute`` chain back to its root ``Name`` node and return
    that name. Returns ``None`` if the root is not a simple Name (e.g. the
    chain starts from a Call or a Subscript).
    """
    current = node
    while isinstance(current, ast.Attribute):
        current = current.value
    if isinstance(current, ast.Name):
        return current.id
    return None


def _validate_write_target(
    node: ast.AST,
    allowed_names: Mapping[str, Any],
    declared_vars: Set[str],
) -> None:
    """Refuse a write (``x.attr = v`` / ``x[k] = v``) that can reach shared state.

    Everything in ``allowed_names`` lives for the whole process and is handed
    to every upload, so ``datetime.datetime = 1`` or ``Class.validate = 1``
    would poison every later import, for every user. A write is accepted only
    when its chain starts at a variable this script itself declared (and that
    is not also an injected name). Aliasing a shared object through such a
    variable (``d = datetime; d.datetime = 1``) is caught at run time by
    ``_guarded_setattr``.
    """
    if not isinstance(node.ctx, ast.Store):
        raise SafeBumlLoaderError("Deleting attributes or items is not allowed in BUML")
    root_node = node
    while isinstance(root_node, (ast.Attribute, ast.Subscript)):
        root_node = root_node.value
    if not isinstance(root_node, ast.Name):
        raise SafeBumlLoaderError(
            "Assignment must target an attribute of a variable declared in the BUML file"
        )
    root = root_node.id
    if root in allowed_names or root not in declared_vars:
        raise SafeBumlLoaderError(
            f"Assignment to an attribute or item of {root!r} is not allowed: "
            "only variables declared in the BUML file may be modified"
        )


def _validate_node(
    node: ast.AST,
    allowed_names: Mapping[str, Any],
    declared_vars: Set[str],
    depth: int = 0,
    in_nameerror_guard: bool = False,
) -> None:
    """
    Recursively validate ``node``. Raises ``SafeBumlLoaderError`` on anything
    outside our allowlist.

    ``allowed_names`` is the fixed set of names that may appear as the root
    of any name reference (the injected BUML classes + helper constants).
    ``declared_vars`` is the set of variable names assigned earlier in this
    same file; a reference to ``x.foo()`` is only allowed if ``x`` is in
    ``allowed_names`` or ``declared_vars``.
    """
    if depth > _MAX_AST_DEPTH:
        raise SafeBumlLoaderError(
            f"BUML AST too deep (> {_MAX_AST_DEPTH} levels)"
        )
    node_type = type(node)
    if node_type not in _ALLOWED_NODE_TYPES:
        raise SafeBumlLoaderError(
            f"Disallowed AST node: {node_type.__name__}"
        )

    if isinstance(node, ast.BinOp):
        if type(node.op) not in _ALLOWED_BINOPS:
            raise SafeBumlLoaderError(
                f"Disallowed binary operator: {type(node.op).__name__}"
            )

    if isinstance(node, ast.UnaryOp):
        if type(node.op) not in _ALLOWED_UNARY_OPS:
            raise SafeBumlLoaderError(
                f"Disallowed unary operator: {type(node.op).__name__}"
            )

    if isinstance(node, ast.Attribute):
        if _is_dunder(node.attr):
            raise SafeBumlLoaderError(
                f"Access to dunder/underscore attribute is forbidden: {node.attr!r}"
            )
        if node.attr in _FORBIDDEN_ATTRIBUTES:
            raise SafeBumlLoaderError(
                f"Access to attribute {node.attr!r} is not allowed in BUML"
            )
        # A literal has no place at the root of an attribute chain: its methods
        # (string formatting above all) reach object internals that the
        # per-node checks never see.
        base = node
        while isinstance(base, ast.Attribute):
            base = base.value
        if isinstance(base, (ast.Constant, ast.JoinedStr)):
            raise SafeBumlLoaderError(
                "Attribute access on a literal is not allowed in BUML"
            )
        # The root of the attribute chain must resolve to an allowed name or
        # a previously declared variable. This blocks ``os.system`` style
        # calls when ``os`` is not in the allowed dict.
        root = _attribute_root_name(node)
        if root is not None:
            if (root not in allowed_names and root not in declared_vars
                    and not in_nameerror_guard):
                raise SafeBumlLoaderError(
                    f"Attribute access on unknown name: {root!r}"
                )

    if isinstance(node, (ast.Attribute, ast.Subscript)) and not isinstance(node.ctx, ast.Load):
        _validate_write_target(node, allowed_names, declared_vars)

    if isinstance(node, ast.Name):
        # Store-context names are fine (we collect them separately); only
        # Load-context references need to resolve to something we allow.
        if isinstance(node.ctx, ast.Load):
            # Inside `try: ... except NameError: pass` an unresolved name is the
            # POINT. Safe: it resolves at runtime against the same controlled
            # namespace, or raises NameError and is swallowed by that `pass`.
            if (node.id not in allowed_names and node.id not in declared_vars
                    and not in_nameerror_guard):
                raise SafeBumlLoaderError(
                    f"Reference to unknown name: {node.id!r}"
                )
            if _is_dunder(node.id):
                raise SafeBumlLoaderError(
                    f"Reference to underscore/dunder name is forbidden: {node.id!r}"
                )
            if node.id in _EXCEPTION_NAMES:
                # Legal only in the handler's `except <type>:` slot, which is
                # validated by _validate_try_shape and skipped by the walk.
                # Binding it to a value has no use in BUML and would hand out
                # a class object to introspect from.
                raise SafeBumlLoaderError(
                    f"{node.id!r} may only appear as an except clause type"
                )

    if isinstance(node, ast.Try):
        _validate_try_shape(node)

    if isinstance(node, ast.Call):
        func = node.func
        if isinstance(func, ast.Name):
            if func.id not in allowed_names and func.id not in declared_vars:
                raise SafeBumlLoaderError(
                    f"Call to unknown function: {func.id!r}"
                )
        elif isinstance(func, ast.Attribute):
            # Method call like ``domain_model.types.add(cls1)``.
            # Both the dunder check and the root check are handled by the
            # generic Attribute validation above; nothing extra here.
            pass
        else:
            raise SafeBumlLoaderError(
                "Only calls to named functions or attribute chains are allowed"
            )

    # Recurse into children. Use ``iter_child_nodes`` so we cover all
    # AST-significant children without hitting string fields.
    guarded = in_nameerror_guard or isinstance(node, ast.Try)
    for child in ast.iter_child_nodes(node):
        # The handler's exception type is already pinned to `NameError` by
        # _validate_try_shape; re-walking it would trip the _EXCEPTION_NAMES
        # rule that stops it being used as a value anywhere else.
        if isinstance(node, ast.ExceptHandler) and child is node.type:
            continue
        _validate_node(child, allowed_names, declared_vars, depth + 1, guarded)


# Name under which the run-time write guard is placed in the exec globals. The
# leading underscore makes it unreachable from user content: the validator
# rejects every underscore name before the rewrite below introduces this one.
_SETATTR_GUARD_NAME = "_besser_guarded_setattr"

# Objects that are never a fresh model element built by the script: classes,
# modules, namespaces and anything callable that is not an instance. Writing to
# one of these changes behaviour for the whole process.
_SHARED_OBJECT_TYPES = (
    type,
    types.ModuleType,
    types.SimpleNamespace,
    types.FunctionType,
    types.BuiltinFunctionType,
    types.MethodType,
    types.BuiltinMethodType,
    property,
    classmethod,
    staticmethod,
)


def _metamodel_singleton_ids() -> Set[int]:
    """Ids of the metamodel's module-level instances (``StringType`` & co.).

    An upload can reach them without naming them, e.g. as the ``type`` of
    ``Property(name="a", type="str")``.
    """
    ids: Set[int] = set()
    for module_name, module in list(sys.modules.items()):
        if module is None or not module_name.startswith("besser.BUML.metamodel"):
            continue
        for attr_name, value in vars(module).items():
            if not attr_name.startswith("_") and not isinstance(value, _SHARED_OBJECT_TYPES):
                ids.add(id(value))
    return ids


def _make_guarded_setattr(protected: Mapping[str, Any]):
    """Build the run-time check behind every ``<expr>.<attr> = <value>``.

    The static check only sees names; ``d = datetime; d.datetime = 1`` reaches
    the shared object through a variable the script declared. At run time the
    actual target object is known, so it is refused when it is one of the
    injected objects or of a kind that is never a per-upload model element.
    """
    protected_ids = {id(value) for value in protected.values()} | _metamodel_singleton_ids()

    def _guarded_setattr(target: Any, attr: str, value: Any) -> None:
        if id(target) in protected_ids or isinstance(target, _SHARED_OBJECT_TYPES):
            raise SafeBumlLoaderError(
                f"Assignment to attribute {attr!r} of a shared object is not allowed in BUML"
            )
        setattr(target, attr, value)

    return _guarded_setattr


def _check_assignment_shapes(module: ast.Module) -> None:
    """Attribute writes must be the single target of a plain assignment.

    That is the only shape the builders emit (``var.attr = value``), and the
    only one ``_GuardAttributeWrites`` rewrites, so ``a = b.x = v`` and
    ``x, y.z = ...`` are refused rather than left unguarded.
    """
    for stmt in ast.walk(module):
        if isinstance(stmt, ast.Assign):
            targets = stmt.targets
            if len(targets) > 1 or not isinstance(targets[0], (ast.Name, ast.Attribute)):
                for target in targets:
                    if any(isinstance(n, (ast.Attribute, ast.Subscript)) for n in ast.walk(target)):
                        raise SafeBumlLoaderError(
                            "Attribute assignment must be a single, plain target in BUML"
                        )
        elif isinstance(stmt, ast.AnnAssign):
            if isinstance(stmt.target, (ast.Attribute, ast.Subscript)) and stmt.value is None:
                raise SafeBumlLoaderError(
                    "Annotated attribute declaration without a value is not allowed in BUML"
                )


class _GuardAttributeWrites(ast.NodeTransformer):
    """Rewrite ``obj.attr = value`` to ``_besser_guarded_setattr(obj, "attr", value)``."""

    def _rewrite(self, stmt: ast.stmt, target: ast.Attribute, value: ast.expr) -> ast.stmt:
        obj = target.value
        call = ast.Call(
            func=ast.Name(id=_SETATTR_GUARD_NAME, ctx=ast.Load()),
            args=[_as_load(obj), ast.Constant(value=target.attr), value],
            keywords=[],
        )
        return ast.copy_location(ast.Expr(value=call), stmt)

    def visit_Assign(self, node: ast.Assign) -> ast.stmt:
        if len(node.targets) == 1 and isinstance(node.targets[0], ast.Attribute):
            return self._rewrite(node, node.targets[0], node.value)
        return node

    def visit_AnnAssign(self, node: ast.AnnAssign) -> ast.stmt:
        if isinstance(node.target, ast.Attribute) and node.value is not None:
            return self._rewrite(node, node.target, node.value)
        return node


def _as_load(node: ast.expr) -> ast.expr:
    """Return ``node`` with every context switched to ``Load``."""
    for sub in ast.walk(node):
        if hasattr(sub, "ctx"):
            sub.ctx = ast.Load()
    return node


def _import_aliases(stmt: ast.Import | ast.ImportFrom, allowed_names: Mapping[str, Any]) -> Dict[str, Any]:
    """Return the names an ``X as Y`` import binds to an allowed object.

    The import itself never runs. An alias of a name outside ``allowed_names``
    binds nothing, so using it fails like any unknown name.
    """
    aliases: Dict[str, Any] = {}
    for alias in stmt.names:
        if alias.asname is None or alias.asname == alias.name:
            continue
        if _is_dunder(alias.asname):
            raise SafeBumlLoaderError(
                f"Import alias to underscore/dunder name is forbidden: {alias.asname!r}"
            )
        if alias.name in allowed_names:
            aliases[alias.asname] = allowed_names[alias.name]
    return aliases


def _collect_assigned_names(module: ast.Module) -> Set[str]:
    """
    Pre-scan the module for top-level assignments and collect every variable
    name they bind. This lets later expressions reference ``domain_model``,
    ``cls1``, etc. even if the assignment comes lexically later in the file
    (which doesn't happen for BUML output, but is safe to permit).
    """
    names: Set[str] = set()
    for stmt in module.body:
        if isinstance(stmt, ast.Assign):
            for target in stmt.targets:
                if isinstance(target, ast.Name):
                    names.add(target.id)
                elif isinstance(target, (ast.Tuple, ast.List)):
                    for element in target.elts:
                        if isinstance(element, ast.Name):
                            names.add(element.id)
        elif isinstance(stmt, ast.AnnAssign):
            # Annotated assignments only have a single target.
            if isinstance(stmt.target, ast.Name):
                names.add(stmt.target.id)
        elif isinstance(stmt, ast.FunctionDef):
            names.add(stmt.name)
    return names


def _local_names(func: ast.FunctionDef) -> Set[str]:
    """The parameters of ``func`` and every name its body assigns."""
    args = func.args
    names = {a.arg for a in args.posonlyargs + args.args + args.kwonlyargs}
    names |= _collect_assigned_names(ast.Module(body=func.body, type_ignores=[]))
    return names


def _validate_function(
    func: ast.FunctionDef, allowed_names: Mapping[str, Any], declared_vars: Set[str],
) -> None:
    """Accept a plain top-level helper: no decorators, ``*args`` / ``**kwargs``
    or nested definitions, and a body that passes the same validation as the
    module (``return`` included). Its parameters and locals count as declared."""
    if func.decorator_list:
        raise SafeBumlLoaderError("a decorated function is not allowed in BUML")
    if func.args.vararg or func.args.kwarg:
        raise SafeBumlLoaderError("*args / **kwargs are not allowed in BUML")
    if _is_dunder(func.name):
        raise SafeBumlLoaderError(f"Function name may not start with an underscore: {func.name!r}")
    local_vars = declared_vars | _local_names(func)
    for name in local_vars - declared_vars:
        if _is_dunder(name):
            raise SafeBumlLoaderError(f"Underscore/dunder name is forbidden: {name!r}")
    args = func.args
    for expr in [*args.defaults, *(d for d in args.kw_defaults if d is not None),
                 *(a.annotation for a in args.posonlyargs + args.args + args.kwonlyargs if a.annotation),
                 *([func.returns] if func.returns else [])]:
        _validate_node(expr, allowed_names, declared_vars)
    for stmt in func.body:
        _validate_node(stmt, allowed_names, local_vars)


def _loaded_names(node: ast.AST) -> Set[str]:
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)}


def _stored_names(stmt: ast.stmt) -> Set[str]:
    if isinstance(stmt, ast.FunctionDef):
        return {stmt.name}
    return {n.id for n in ast.walk(stmt) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)}


def _bound_names(tree: ast.Module) -> Set[str]:
    """Every name the file binds anywhere: assignments, loop targets, functions, parameters."""
    names: Set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
            names.add(node.id)
        elif isinstance(node, ast.FunctionDef):
            names.add(node.name)
        elif isinstance(node, ast.arg):
            names.add(node.arg)
    return names


def _value_root(stmt: ast.stmt) -> Optional[str]:
    """The name a statement's value starts from: ``Class`` in ``b = Class(...)``,
    ``gen`` in ``gen.generate()``. ``None`` for a literal or a container."""
    value = getattr(stmt, "value", None) if isinstance(
        stmt, (ast.Assign, ast.AnnAssign, ast.Expr, ast.Return)) else None
    while isinstance(value, (ast.Call, ast.Attribute, ast.Subscript)):
        value = value.func if isinstance(value, ast.Call) else value.value
    return value.id if isinstance(value, ast.Name) else None


def _skip_runner_statements(
    body: list, known: Set[str], source: str, warnings: Optional[list],
) -> list:
    """Drop the statements of ``body`` that run the script instead of building the model.

    A statement is skipped when it uses a name that is neither B-UML nor bound by
    the file (``print``, a generator class, ``os``), or a variable only skipped
    statements set, unless it builds a model element: an assignment or call that
    starts from a B-UML name or a kept variable is kept, so a typo such as
    ``Proprety(...)`` is an error that names the variable, not a missing class.
    Skipped statements never run. Returns the kept statements.
    """
    skipped: Dict[int, str] = {}  # statement index -> why it runs the script
    runner_vars: Set[str] = set()
    while True:
        changed = False
        for index, stmt in enumerate(body):
            if index in skipped or isinstance(stmt, ast.FunctionDef):
                continue
            bad = sorted(n for n in _loaded_names(stmt) if n not in known or n in runner_vars)
            if not bad:
                continue
            root = _value_root(stmt)
            builds_model = (isinstance(stmt, (ast.Assign, ast.AnnAssign, ast.Expr, ast.Return))
                            and (root is None or (root in known and root not in runner_vars)))
            if builds_model:
                continue
            name = root if root in bad else bad[0]
            skipped[index] = (f"it uses {name!r}, which is set by a skipped line" if name in runner_vars
                              else f"it uses {name!r}, which is not part of B-UML")
            changed = True
        kept_stores = set().union(*(_stored_names(s) for i, s in enumerate(body) if i not in skipped))
        runner_vars = set().union(*(_stored_names(body[i]) for i in skipped)) - kept_stores
        if not changed:
            break

    for index in sorted(skipped):
        stmt = body[index]
        snippet = (ast.get_source_segment(source, stmt) or "").splitlines()[0][:80]
        message = (f"Skipped line {stmt.lineno} ({snippet}): {skipped[index]}, "
                   "so it runs the script rather than building the model")
        logger.warning("BUML import: %s", message)
        if warnings is not None:
            warnings.append(message)

    kept = [s for i, s in enumerate(body) if i not in skipped]
    for stmt in kept:
        for name in sorted(_loaded_names(stmt) & runner_vars):
            line = next(body[i].lineno for i in sorted(skipped) if name in _stored_names(body[i]))
            raise SafeBumlLoaderError(
                f"line {stmt.lineno}: {name!r} is set on line {line}, which was skipped because it "
                f"uses a name that is not part of B-UML"
            )
    return kept


def safe_load_buml(
    content: str,
    allowed_names: Mapping[str, Any],
    max_ast_nodes: int = _MAX_AST_NODES,
    max_content_chars: int = _MAX_CONTENT_BYTES,
    shadowable_names: Optional[Mapping[str, Any]] = None,
    warnings: Optional[list] = None,
) -> Dict[str, Any]:
    """
    Parse ``content`` as Python, validate against the allowlist, and execute
    the validated tree in a frozen namespace. Returns the dict of local
    variables produced by execution.

    Parameters
    ----------
    content:
        The BUML source. Top-level imports are skipped, not executed.
    allowed_names:
        Mapping of names that may appear at the top level of an expression.
        Typically the BUML classes and helper constants the file constructs.
        A module value is dropped, so its name is refused like any unknown
        one: a module hands over everything it imported (an upload could
        reach ``knowledge_graph.copy.dispatch_table.clear()`` and change
        interpreter-wide state). Callers may therefore build the mapping
        from ``dir(package)``, which lists submodules too.
    max_ast_nodes:
        Cap on the number of AST nodes. A trace is a long flat list of
        constructor calls and gets a higher one; the depth cap still applies.
    max_content_chars:
        Cap on the source size. A trace section gets the size of a whole
        project file, which it can fill.
    shadowable_names:
        Names allowed like ``allowed_names`` unless the content assigns a
        variable of that name: then the name is the content's variable only.
        For a file whose models may use them (a class called ``Person`` in a
        project file with a trace written before its metaclasses got aliases).
    warnings:
        Given for a hand-written script (a model ``.py`` a user uploads): its
        ``if __name__ == "__main__":`` body is loaded, and each statement that
        runs the script rather than building the model is skipped and reported
        here (see _skip_runner_statements). Without it, such a statement is
        refused and the main block is stripped.

    Returns
    -------
    dict
        The local variables produced during execution, for the caller to
        inspect and pluck out the model instance.

    Raises
    ------
    SafeBumlLoaderError
        If the AST contains a disallowed construct.
    SyntaxError
        If the content is not parseable Python.
    """
    # Fail fast on oversized uploads before we spend memory on parsing.
    # ``len(content)`` is char count; bytes would be >= char count for
    # UTF-8 so this is a conservative cap.
    if len(content) > max_content_chars:
        raise SafeBumlLoaderError(
            f"BUML content too large ({len(content)} chars > {max_content_chars})"
        )

    allowed_names = {
        name: value for name, value in allowed_names.items()
        if not isinstance(value, types.ModuleType)
    }

    source = content.removeprefix("﻿")
    tree = ast.parse(source, mode="exec")

    def _is_main_guard(stmt) -> bool:
        """True for exactly ``if __name__ == "__main__":`` (either order)."""
        if not isinstance(stmt, ast.If) or not isinstance(stmt.test, ast.Compare):
            return False
        test = stmt.test
        if len(test.ops) != 1 or not isinstance(test.ops[0], ast.Eq):
            return False
        operands = [test.left] + list(test.comparators)
        names = [o.id for o in operands if isinstance(o, ast.Name)]
        consts = [o.value for o in operands if isinstance(o, ast.Constant)]
        return names == ["__name__"] and consts == ["__main__"]

    # Defence-in-depth: cap the total node count even if everything is
    # on the allowlist. A file full of legitimately-allowed ``Call``
    # nodes could still exhaust memory during traversal otherwise.
    # One ``id="..."`` keyword per call is not counted, so a model that fits
    # without element ids also fits with them. A repeated ``id=`` parses (it
    # only fails at compile time), so the others still count.
    node_count = 0
    for node in ast.walk(tree):
        node_count += 1
        if isinstance(node, ast.Call) and any(
            kw.arg == "id" and isinstance(kw.value, ast.Constant) and isinstance(kw.value.value, str)
            for kw in node.keywords
        ):
            node_count -= 2  # the keyword and its string
    if node_count > max_ast_nodes:
        raise SafeBumlLoaderError(
            f"BUML AST too complex ({node_count} nodes > {max_ast_nodes})"
        )

    # Imports are dropped (see _import_aliases). A hand-written script (the
    # caller passes ``warnings``): the body of ``if __name__ == "__main__":`` is
    # loaded like top-level code, since scripts often build the model there, and
    # statements that run the script rather than build the model are skipped
    # (_skip_runner_statements). Machine-written content (no ``warnings``): the
    # main block is stripped, never run, and anything else is refused.
    script = warnings is not None
    body = []
    aliases: Dict[str, Any] = {}
    for stmt in tree.body:
        if _is_main_guard(stmt):
            if script:
                body.extend(stmt.body)
        elif isinstance(stmt, (ast.Import, ast.ImportFrom)):
            aliases.update(_import_aliases(stmt, allowed_names))
        else:
            body.append(stmt)
    known = set(allowed_names) | set(aliases) | set(shadowable_names or {}) | _bound_names(tree)
    if script:
        body = _skip_runner_statements(body, known, source, warnings)
    for stmt in body:
        if isinstance(stmt, ast.FunctionDef) and script:
            stmt.body = _skip_runner_statements(stmt.body, known, source, warnings) or [ast.Pass()]
        elif not isinstance(stmt, _TOP_LEVEL_STATEMENTS) or isinstance(stmt, ast.FunctionDef):
            kind = type(stmt).__name__
            raise SafeBumlLoaderError(
                f"Top-level statement not allowed: {kind} (line {stmt.lineno}): "
                f"{_STATEMENT_NAMES.get(kind, kind)} is not supported in an imported B-UML file, "
                "which may only assign and call B-UML constructors"
                + (" and helper functions" if script else "")
            )
    tree.body = body
    allowed_names = {**allowed_names, **aliases}

    declared_vars = _collect_assigned_names(tree)
    allowed_names = {
        **{name: value for name, value in (shadowable_names or {}).items()
           if name not in declared_vars and not isinstance(value, types.ModuleType)},
        **allowed_names,
    }

    # Reject any overlap between declared vars and allowed builtins that
    # contain characters forbidden elsewhere (e.g. starting with ``_``).
    for name in declared_vars:
        if _is_dunder(name):
            raise SafeBumlLoaderError(
                f"Assignment to underscore/dunder name is forbidden: {name!r}"
            )

    for stmt in tree.body:
        try:
            if isinstance(stmt, ast.FunctionDef):
                _validate_function(stmt, allowed_names, declared_vars)
            else:
                _validate_node(stmt, allowed_names, declared_vars)
        except SafeBumlLoaderError as error:
            raise SafeBumlLoaderError(f"line {stmt.lineno}: {error}") from None
    _check_assignment_shapes(tree)

    # Every attribute write goes through a run-time check of the real target
    # object; see _make_guarded_setattr.
    tree = _GuardAttributeWrites().visit(tree)
    # Every call of a helper function counts against _MAX_FUNCTION_CALLS.
    for stmt in tree.body:
        if isinstance(stmt, ast.FunctionDef):
            stmt.body.insert(0, ast.Expr(value=ast.Call(
                func=ast.Name(id=_CALL_COUNTER_NAME, ctx=ast.Load()), args=[], keywords=[])))

    # Re-parse with location info preserved (ast.parse already did this, but
    # fix_missing_locations is cheap insurance for manually constructed ASTs).
    ast.fix_missing_locations(tree)

    code = compile(tree, filename="<buml>", mode="exec")

    # Execute with a near-empty ``__builtins__`` so user content cannot reach
    # any built-in helpers; everything it needs must be in ``allowed_names``.
    # The one exception is the ``NameError`` class, which the guard our builders
    # emit must resolve. It is an exception type, not a callable that reaches
    # anything, and the validator pins that handler to a literal ``pass``.
    globals_ns: Dict[str, Any] = {"__builtins__": {"NameError": NameError}}
    globals_ns.update(allowed_names)
    # A fresh ``datetime`` stand-in per load, so nothing an upload does to it
    # can be seen by another upload.
    for name, value in allowed_names.items():
        if value is SAFE_DATETIME_MODULE:
            globals_ns[name] = make_safe_datetime_module()
    globals_ns[_SETATTR_GUARD_NAME] = _make_guarded_setattr(globals_ns)
    globals_ns[_CALL_COUNTER_NAME] = _make_call_counter()
    # One namespace, as in a module: a helper function sees the file's other
    # functions and variables. What the file bound is returned, not what was injected.
    injected = dict(globals_ns)
    exec(code, globals_ns)  # noqa: S102 - AST pre-validated above
    return {
        name: value for name, value in globals_ns.items()
        if name != "__builtins__" and (name not in injected or value is not injected[name])
    }


def _make_call_counter():
    """Count calls of the file's helper functions; refuse past _MAX_FUNCTION_CALLS."""
    calls = [0]

    def _count_call() -> None:
        calls[0] += 1
        if calls[0] > _MAX_FUNCTION_CALLS:
            raise SafeBumlLoaderError(
                f"BUML helper functions made more than {_MAX_FUNCTION_CALLS} calls"
            )

    return _count_call
