"""Credential redaction for generated artifacts and streamed run events.

The user's BYOK credential is never intentionally passed to the model, but a
generated project can still contain a credential copied from imported content
or invented/pasted in an instruction.  Treat the artifact and SSE serializers
as the final trust boundary: remove populated ``.env`` files and replace
credential-shaped text everywhere else with a stable placeholder.
"""

from __future__ import annotations

import fnmatch
import ipaddress
import logging
import math
import os
import re
import tomllib
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable

import yaml

from besser.spec_driven_agent.execution.workspace_fs import open_plain, open_plain_write, walk_plain

logger = logging.getLogger(__name__)

REDACTED_SECRET = "[REDACTED]"
_MAX_TEXT_FILE_BYTES = 2 * 1024 * 1024

# .env-family files whose content is safe to publish when it only contains
# placeholders. They are still scanned and redacted if a real token appears.
_ENV_SAFE_SUFFIXES = (".example", ".sample", ".template", ".dist")

_SECRET_ENV_ASSIGNMENT_RE = re.compile(
    r"(?im)^(\s*[A-Za-z0-9_]*"
    r"(?:API[_-]?KEY|SECRET|TOKEN|PASSWORD|PASSWD|PRIVATE[_-]?KEY|ACCESS[_-]?KEY)"
    r"[A-Za-z0-9_]*\s*=\s*)([^\r\n]+)$"
)

# Provider tokens with sufficiently specific prefixes to avoid redacting
# ordinary prose or generated identifiers.
_SECRET_VALUE_TOKEN_RE = re.compile(
    # The lookbehind keeps "sk-" from matching inside kebab-case identifiers
    # (e.g. `./task-list-item-component`).
    r"(?<![A-Za-z0-9_\-])"
    r"(sk-ant-[A-Za-z0-9_\-]{12,}"
    r"|sk-[A-Za-z0-9_\-]{16,}"
    r"|gh[posru]_[A-Za-z0-9]{20,}"
    r"|AKIA[0-9A-Z]{16}"
    r"|xox[baprs]-[A-Za-z0-9-]{10,})"
)

# The prefix-anchored rules of gitleaks (MIT), regenerated by
# data/vendor_gitleaks_rules.py. Prefix-less rules are left out on purpose:
# redaction rewrites source code, and a false hit breaks the app.
_GITLEAKS_RULES_PATH = Path(__file__).with_name("data") / "gitleaks_rules.toml"

# A database URL's password: ``scheme://user:password@host`` (the user may be
# empty: ``redis://:pw@host``). A password for a local host is left alone: it
# only opens the user's own container, and the generated docker-compose sets
# the same value on the database, so redacting it breaks the app.
_DB_URL_PASSWORD_RE = re.compile(
    r"(?i)\b(?:postgres(?:ql)?|mysql|mariadb|mssql|oracle|mongodb(?:\+srv)?|rediss?|amqps?)"
    r"(?:\+[a-z0-9]+)?://[^:/?#@\s'\"]*:(?P<password>[^@/?#\s'\"]+)@(?P<host>[^:/?#,\s'\"]*)"
)
# Code that builds a URL rather than holding one: ``{settings.db_password}``,
# ``%s``, ``%(password)s``, ``${DB_PASSWORD}``, ``$DB_PASSWORD``.
_URL_TEMPLATE_RE = re.compile(r"[{}]|%(?:\(\w+\))?[sdr]|^\$")
_LOCAL_HOST_SUFFIXES = (".localhost", ".local", ".docker.internal")

# A private key, also one cut before its END line (an excerpt, a streamed
# tool call), which the gitleaks rule misses: the header and the base64 after it.
_PEM_PRIVATE_KEY_RE = re.compile(
    r"-----BEGIN[ A-Z0-9_-]{0,100}PRIVATE KEY(?: BLOCK)?-----(?:\s|\\[nr]|[A-Za-z0-9+/=]){64,}"
    r"(?:-----END[ A-Z0-9_-]{0,100}PRIVATE KEY(?: BLOCK)?-----)?"
)
# No value rule matches fewer characters (``redis://:x@``), so a shorter
# string skips them: most strings of an SSE frame are short field values.
_MIN_VALUE_SECRET_LENGTH = 10

_ENV_PLACEHOLDER_VALUES = {
    "",
    REDACTED_SECRET.lower(),
    "changeme",
    "change-me",
    "your-key-here",
    "your_api_key",
    "xxx",
    "xxxx",
    "todo",
    "...",
    "none",
    "null",
}


def _is_placeholder(value: str) -> bool:
    normalized = value.strip().strip('"').strip("'").strip()
    lowered = normalized.lower()
    return (
        lowered in _ENV_PLACEHOLDER_VALUES
        or normalized.startswith("${")
        or normalized.startswith("<")
        or "your" in lowered
        or "placeholder" in lowered
        or "example" in lowered
    )


@dataclass(frozen=True)
class _Allowlist:
    """A gitleaks allowlist: a match it allows is not a secret."""
    regexes: tuple[re.Pattern[str], ...]
    stopwords: tuple[str, ...]
    target: str  # what ``regexes`` test: "secret", "match" or "line"
    require_all: bool

    def allows(self, secret: str, match: str, line: str) -> bool:
        text = {"match": match, "line": line}.get(self.target, secret)
        checks = []
        if self.regexes:
            checks.append(any(regex.search(text) for regex in self.regexes))
        if self.stopwords:
            checks.append(any(word in secret.lower() for word in self.stopwords))
        return all(checks) if self.require_all else any(checks)


@dataclass(frozen=True)
class _TokenRule:
    id: str
    regex: re.Pattern[str]
    keywords: tuple[str, ...]  # lower-case; the rule runs only when one occurs
    secret_group: int  # 0: gitleaks' default, the first non-empty group
    entropy: float
    allowlists: tuple[_Allowlist, ...]


def _allowlist(config: dict) -> _Allowlist:
    return _Allowlist(
        regexes=tuple(re.compile(pattern, re.ASCII) for pattern in config.get("regexes", ())),
        stopwords=tuple(word.lower() for word in config.get("stopwords", ())),
        target=config.get("regexTarget", "secret"),
        require_all=config.get("condition") == "AND",
    )


def _load_token_rules(path: Path) -> tuple[_Allowlist, tuple[_TokenRule, ...]]:
    """The vendored rules, compiled with ``re.ASCII``: Go's word classes are ASCII-only."""
    with open(path, "rb") as handle:
        config = tomllib.load(handle)
    rules = tuple(
        _TokenRule(
            id=rule["id"],
            regex=re.compile(rule["regex"], re.ASCII),
            keywords=tuple(rule.get("keywords", ())),
            secret_group=rule.get("secretGroup", 0),
            entropy=rule.get("entropy", 0.0),
            allowlists=tuple(_allowlist(allowlist) for allowlist in rule.get("allowlists", ())),
        )
        for rule in config["rules"]
    )
    return _allowlist(config["allowlist"]), rules


_GLOBAL_ALLOWLIST, _TOKEN_RULES = _load_token_rules(_GITLEAKS_RULES_PATH)


def _trie_pattern(words: Iterable[str]) -> str:
    """An alternation of ``words`` shaped as a trie, so ``re`` tests each
    character once per position instead of once per word (~7x faster here)."""
    trie: dict = {}
    for word in words:
        node = trie
        for char in word:
            node = node.setdefault(char, {})
        node[""] = {}

    def emit(node: dict) -> str:
        branches = [re.escape(char) + emit(child) for char, child in sorted(node.items()) if char]
        if not branches:
            return ""
        body = branches[0] if len(branches) == 1 else "(?:" + "|".join(branches) + ")"
        return f"(?:{body})?" if "" in node else body

    return emit(trie)


_KEYWORDS = sorted({keyword for rule in _TOKEN_RULES for keyword in rule.keywords})
# The lookahead finds the longest keyword at every position; the shorter
# keywords that are its prefixes occur there too.
_KEYWORD_RE = re.compile("(?=(" + _trie_pattern(_KEYWORDS) + "))")
_KEYWORD_PREFIXES = {keyword: {k for k in _KEYWORDS if keyword.startswith(k)} for keyword in _KEYWORDS}
_RULE_INDEXES_BY_KEYWORD = {
    keyword: {index for index, rule in enumerate(_TOKEN_RULES) if keyword in rule.keywords}
    for keyword in _KEYWORDS}


def _keywords_in(lowered: str) -> set[str]:
    """Every rule keyword that occurs in ``lowered``, in one pass."""
    found: set[str] = set()
    for match in _KEYWORD_RE.finditer(lowered):
        found |= _KEYWORD_PREFIXES[match.group(1)]
    return found


def _shannon_entropy(text: str) -> float:
    counts = Counter(text)
    return -sum(n / len(text) * math.log2(n / len(text)) for n in counts.values())


def _secret_span(rule: _TokenRule, match: re.Match[str]) -> tuple[int, int]:
    group = rule.secret_group or next(
        (number for number in range(1, rule.regex.groups + 1) if match.group(number)), 0)
    return match.span(group)


def _is_rule_secret(rule: _TokenRule, secret: str, match: re.Match[str]) -> bool:
    text = match.string
    line_start = text.rfind("\n", 0, match.start()) + 1
    line_end = text.find("\n", match.end())
    line = text[line_start:line_end if line_end >= 0 else len(text)]
    return not (
        (rule.entropy and _shannon_entropy(secret) <= rule.entropy)  # as gitleaks skips it
        or _is_placeholder(secret)
        or _GLOBAL_ALLOWLIST.allows(secret, match.group(0), line)
        or any(allowlist.allows(secret, match.group(0), line) for allowlist in rule.allowlists)
    )


def _redact_rule_matches(rule: _TokenRule, text: str) -> tuple[str, int]:
    pieces, end, findings = [], 0, 0
    for match in rule.regex.finditer(text):
        start, stop = _secret_span(rule, match)
        if start < end or start == stop or not _is_rule_secret(rule, text[start:stop], match):
            continue
        pieces += [text[end:start], REDACTED_SECRET]
        end, findings = stop, findings + 1
    return ("".join(pieces) + text[end:], findings) if findings else (text, 0)


def _redact_vendored_tokens(text: str) -> tuple[str, int]:
    indexes = set().union(*(_RULE_INDEXES_BY_KEYWORD[keyword] for keyword in _keywords_in(text.lower())))
    findings = 0
    for index in sorted(indexes):  # in vendored order, as when every rule ran
        text, count = _redact_rule_matches(_TOKEN_RULES[index], text)
        findings += count
    return text, findings


def _redact_db_url_passwords(text: str) -> tuple[str, int]:
    findings = 0

    def _replacement(match: re.Match[str]) -> str:
        nonlocal findings
        password, host = match.group("password"), match.group("host")
        if (_URL_TEMPLATE_RE.search(password) or _URL_TEMPLATE_RE.search(host)
                or _is_placeholder(password) or _is_local_host(host)):
            return match.group(0)
        findings += 1
        return match.group(0).replace(f":{password}@", f":{REDACTED_SECRET}@")

    return _DB_URL_PASSWORD_RE.sub(_replacement, text), findings


def _is_local_host(host: str) -> bool:
    """A host only the user's own machine reaches: a single label (``db``),
    ``*.localhost``, ``*.local``, ``host.docker.internal``, or a loopback or
    private address."""
    host = host.lower()
    if "." not in host or host.endswith(_LOCAL_HOST_SUFFIXES):
        return True
    try:
        address = ipaddress.ip_address(host)
    except ValueError:
        return False
    return address.is_loopback or address.is_private or address.is_unspecified


# The run's own key is matched literally, so a short value would redact
# ordinary text; real provider keys are far longer.
_MIN_OWN_SECRET_LENGTH = 16


def _own_secrets(secrets: Iterable[str]) -> list[str]:
    """Literal secrets long enough to redact safely, longest first."""
    return sorted({s for s in secrets if s and len(s) >= _MIN_OWN_SECRET_LENGTH},
                  key=len, reverse=True)


def redact_text(
    value: str, *, env_style: bool = True, secrets: Iterable[str] = (),
) -> tuple[str, int]:
    """Return ``value`` with credential material replaced and a match count.

    ``env_style`` controls the NAME-based assignment heuristic, which belongs to
    ``.env`` files only. In source code it matches on the variable NAME and
    swaps the whole value for a bare ``[REDACTED]`` - legal in a .env, an
    undefined name in Python, e.g.:

        SECRET_KEY = [REDACTED]                    # NameError at import
        ACCESS_TOKEN_EXPIRE_MINUTES = [REDACTED]   # an INTEGER, not a secret
        token_data = [REDACTED]                    # a local variable

    With ``env_style=False`` only the value rules run (provider tokens, the
    vendored gitleaks rules, a database URL's password); each replaces the
    secret itself, not the quotes around it, so the file still parses.

    ``secrets`` are literal values (the run's own API key) redacted whatever
    their shape, since a key with no known prefix escapes the token pattern.
    """
    findings = 0
    # Literal secrets first: the token pattern may rewrite part of one.
    for secret in _own_secrets(secrets):
        count = value.count(secret)
        if count:
            value = value.replace(secret, REDACTED_SECRET)
            findings += count

    def _assignment_replacement(match: re.Match[str]) -> str:
        nonlocal findings
        if _is_placeholder(match.group(2)):
            return match.group(0)
        findings += 1
        return match.group(1) + REDACTED_SECRET

    # .env-family content ONLY - see the docstring.
    redacted = value
    if env_style:
        redacted = _SECRET_ENV_ASSIGNMENT_RE.sub(_assignment_replacement, redacted)
    if len(redacted) < _MIN_VALUE_SECRET_LENGTH:
        return redacted, findings
    # Always safe: these match the secret itself, never the quotes around it.
    redacted, token_count = _SECRET_VALUE_TOKEN_RE.subn(REDACTED_SECRET, redacted)
    redacted, pem_count = _PEM_PRIVATE_KEY_RE.subn(REDACTED_SECRET, redacted)
    redacted, vendored_count = _redact_vendored_tokens(redacted)
    redacted, url_count = _redact_db_url_passwords(redacted)
    return redacted, findings + token_count + pem_count + vendored_count + url_count


def redact_data(value: Any, secrets: Iterable[str] = ()) -> tuple[Any, int]:
    """Recursively redact strings in JSON-like event or recipe data."""
    if isinstance(value, str):
        return redact_text(value, secrets=secrets)
    if isinstance(value, list):
        output = []
        findings = 0
        for item in value:
            safe_item, item_findings = redact_data(item, secrets)
            output.append(safe_item)
            findings += item_findings
        return output, findings
    if isinstance(value, tuple):
        safe_list, findings = redact_data(list(value), secrets)
        return tuple(safe_list), findings
    if isinstance(value, dict):
        output = {}
        findings = 0
        for key, item in value.items():
            safe_item, item_findings = redact_data(item, secrets)
            output[key] = safe_item
            findings += item_findings
        return output, findings
    return value, 0


# A field or YAML key that holds a credential: ``openai_api_key``, ``personal_token``,
# ``password``. Anchored at the end so ``max_tokens`` is not one.
_CREDENTIAL_KEY_RE = re.compile(
    r"(?i)(?:^|[_-])(?:api[_-]?key|token|secret|password|passwd|private[_-]?key|access[_-]?key)$"
)
_YAML_ASSIGNMENT_RE = re.compile(r"(?m)^(\s*([A-Za-z0-9_-]+)\s*:[ \t]*)(\S[^\r\n]*)$")


def _redact_yaml_lines(text: str) -> tuple[str, int]:
    """Redact ``key: value`` credential lines, keeping the text as written."""
    findings = 0

    def _replacement(match: re.Match[str]) -> str:
        nonlocal findings
        if not _CREDENTIAL_KEY_RE.search(match.group(2)) or _is_placeholder(match.group(3)):
            return match.group(0)
        findings += 1
        return f"{match.group(1)}'{REDACTED_SECRET}'"

    return _YAML_ASSIGNMENT_RE.sub(_replacement, text), findings


def _is_credential_value(key: Any, value: Any) -> bool:
    return (isinstance(value, (str, int, float)) and not isinstance(value, bool)
            and _CREDENTIAL_KEY_RE.search(str(key)) is not None
            and str(value) != REDACTED_SECRET and not _is_placeholder(str(value)))


def _redact_yaml_data(value: Any) -> tuple[Any, int]:
    """Parsed YAML with every value under a credential key replaced."""
    if isinstance(value, list):
        results = [_redact_yaml_data(item) for item in value]
        return [item for item, _ in results], sum(count for _, count in results)
    if not isinstance(value, dict):
        return value, 0
    output, findings = {}, 0
    for key, item in value.items():
        if _is_credential_value(key, item):
            output[key], findings = REDACTED_SECRET, findings + 1
            continue
        output[key], count = _redact_yaml_data(item)
        findings += count
    return output, findings


def _redact_yaml_credentials(text: str) -> tuple[str, int]:
    """Redact the credentials in a YAML document.

    The line rule keeps the user's formatting but cannot see a credential in a
    list item, a flow mapping (``db: {password: x}``) or a block scalar
    (``api_key: |``). When the parsed result still holds one, the document is
    redacted as data and written again.
    """
    redacted, findings = _redact_yaml_lines(text)
    try:
        if _redact_yaml_data(yaml.safe_load(redacted))[1] == 0:
            return redacted, findings
    except yaml.YAMLError:
        pass  # e.g. a block scalar the line rule cut: read the original instead
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError:
        logger.warning("Agent config is not valid YAML; only its credential lines were redacted")
        return redacted, findings
    safe, count = _redact_yaml_data(data)
    return yaml.safe_dump(safe, sort_keys=False, allow_unicode=True), count


def redact_credentials(value: Any, yaml_fields: Iterable[str] = ()) -> tuple[Any, int]:
    """Redact credentials in JSON-like data: credential-named fields, provider tokens in any
    string, and ``key: value`` credential lines in the string fields named in ``yaml_fields``."""
    yaml_fields = frozenset(yaml_fields)
    if isinstance(value, list):
        results = [redact_credentials(item, yaml_fields) for item in value]
        return [item for item, _ in results], sum(count for _, count in results)
    if isinstance(value, str):
        return redact_text(value, env_style=False)
    if not isinstance(value, dict):
        return value, 0
    output: dict = {}
    findings = 0
    for key, item in value.items():
        if isinstance(item, str) and _CREDENTIAL_KEY_RE.search(str(key)) and not _is_placeholder(item):
            output[key] = REDACTED_SECRET
            findings += 1
            continue
        if isinstance(item, str) and key in yaml_fields:
            item, yaml_findings = _redact_yaml_credentials(item)
            findings += yaml_findings
        output[key], item_findings = redact_credentials(item, yaml_fields)
        findings += item_findings
    return output, findings


def looks_like_secret_env(content: str) -> bool:
    """Whether a non-template ``.env`` body carries a populated credential."""
    _redacted, findings = redact_text(content)
    return findings > 0


@dataclass(frozen=True)
class SecretScrubResult:
    removed_files: tuple[str, ...] = ()
    redacted_files: tuple[str, ...] = ()
    findings: int = 0


def scrub_secret_files(
    workdir: str,
    *,
    excluded_names: Iterable[str] = (),
    secrets: Iterable[str] = (),
) -> SecretScrubResult:
    """Remove populated ``.env`` files and redact secrets in other text files.

    Files are modified in place before they are registered for download or
    copied to GitHub. Symlinks, special files (FIFOs, devices) and files outside
    ``workdir`` are never opened.
    Unreadable, binary, and files larger than 2 MiB are left untouched.
    """
    root_path = os.path.realpath(workdir)
    excluded = tuple(excluded_names)
    secrets = tuple(secrets)
    removed: list[str] = []
    redacted_files: list[str] = []
    findings = 0

    # walk_plain/open_plain skip links and special files: open() on a FIFO
    # the run left behind (``mkfifo``) blocks packaging forever.
    for root, dirs, files in walk_plain(root_path):
        dirs[:] = [
            name
            for name in dirs
            if not any(fnmatch.fnmatch(name, pattern) for pattern in excluded)
        ]
        for name in files:
            if any(fnmatch.fnmatch(name, pattern) for pattern in excluded):
                continue
            full_path = os.path.join(root, name)
            try:
                if os.path.getsize(full_path) > _MAX_TEXT_FILE_BYTES:
                    continue
                with open_plain(full_path, "rb", root=root_path) as handle:
                    raw = handle.read()
                if b"\x00" in raw:
                    continue
                content = raw.decode("utf-8")
            except (OSError, UnicodeDecodeError, ValueError):
                continue

            # File kind is decided BEFORE redacting: the name-based assignment
            # heuristic is a .env rule and destroys source code (see redact_text).
            lowered = name.lower()
            is_env = lowered.startswith(".env")
            safe_content, file_findings = redact_text(
                content, env_style=is_env, secrets=secrets)
            if not file_findings:
                continue

            relative = os.path.relpath(full_path, root_path).replace("\\", "/")
            is_safe_template = any(lowered.endswith(suffix) for suffix in _ENV_SAFE_SUFFIXES)
            if is_env and not is_safe_template:
                try:
                    os.remove(full_path)
                except OSError:
                    continue
                removed.append(relative)
            else:
                try:
                    with open_plain_write(full_path, "w", root=root_path,
                                          encoding="utf-8", newline="") as handle:
                        handle.write(safe_content)
                except OSError:
                    continue
                redacted_files.append(relative)
            findings += file_findings

    return SecretScrubResult(
        removed_files=tuple(removed),
        redacted_files=tuple(redacted_files),
        findings=findings,
    )
