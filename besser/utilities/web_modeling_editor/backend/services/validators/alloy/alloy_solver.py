import logging
import os
import tempfile
from besser.BUML.metamodel.object import ObjectModel
from besser.BUML.metamodel.project import Project
from besser.BUML.metamodel.structural import DomainModel, Metadata
from besser.generators.alloy.alloy_generator import AlloyGenerator
from besser.generators.alloy.alloy_specification import AlloyBounds
from besser.utilities.buml_code_builder.project_builder import project_to_code
from besser.utilities.web_modeling_editor.backend.services.validators.alloy.alloy_analyzer_executor import (
    AlloyAnalyzerExecutor,
    AlloyResult,
)
from besser.utilities.web_modeling_editor.backend.services.validators.alloy.alloy_instance_to_object_model import (
    AlloyInstanceToObjectModel,
)

logger = logging.getLogger(__name__)

class AlloySolver:
    """Performs different kinds of automated analyses on B-UML models annotated with OCL invariants.
    It can check for model consistency (i.e., satisfiability) and generate object diagrams for the model.
    It employs the Alloy Analyzer as a backend for analysis.

    The Alloy specification is generated with :class:`AlloyGenerator` on each analysis.
    When *output_dir* is ``None``, the specification and the Alloy Analyzer's output are written to
    a temporary directory owned by the solver.
    """

    def __init__(self, model: DomainModel, output_dir: str | None = None):
        if output_dir is None:
            self._temp_dir = tempfile.TemporaryDirectory(prefix="besser_alloy_")
            output_dir = self._temp_dir.name
        self.model = model
        self.output_dir = output_dir
        self.alloy_output_dir = os.path.join(self.output_dir, "alloy_output")
        self.generator = AlloyGenerator(model=self.model, output_dir=self.output_dir)
        self.executor = AlloyAnalyzerExecutor()

    def get_scopes(self) -> AlloyBounds | None:
        """Returns what the last analysis searched, ``None`` before any analysis."""
        return self.generator.get_scopes()

    def check_consistency(self, scope: int = 5, seed: int = 0) -> AlloyResult:
        """Execute the Alloy Analyzer and check model satisfiability.
        Returns an AlloyResult indicating whether the model is satisfiable
        (SAT), unsatisfiable (UNSAT), or if the analysis timed out (TIMEOUT).

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            seed: the seed of the random literals generated by the translator.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        self.generator.generate(scope, seed)
        self.specification_path = self.generator.get_specification_path()
        (result, instance_xml_files) = self.executor.generate_instances(self.specification_path, self.alloy_output_dir)
        return result

    def generate_object_models(
        self, scope: int = 5, num_models: int = 1, seed: int = 0
    ) -> tuple[AlloyResult, list[ObjectModel]]:
        """Generates B-UML object models of the model using Alloy.
        Returns an AlloyResult indicating the result of the analysis and a list with
        an object model per satisfying instance found. The list is empty if no satisfying
        instances were found or if the analysis timed out.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            num_models: Number of satisfying instances to request from the Alloy
                Analyzer.
            seed: The seed of the random literals generated by the translator.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        self.generator.generate(scope, seed)
        self.specification_path = self.generator.get_specification_path()
        (result, instance_xml_files) = self.executor.generate_instances(
            self.specification_path, self.alloy_output_dir, num_instances=num_models
        )
        if result != AlloyResult.SAT:
            return result, []
        converter = AlloyInstanceToObjectModel(self.model, self.generator.specification_model)
        object_models = [
            converter.convert(xml_file, name=f"Object_Diagram_{i}")
            for i, xml_file in enumerate(instance_xml_files)
        ]
        return result, object_models

    def generate_project(
        self, scope: int = 5, num_models: int = 1, seed: int = 0
    ) -> tuple[AlloyResult, Project | None]:
        """Generates a B-UML project with the model and object models of it generated using Alloy.
        Returns an AlloyResult indicating the result of the analysis and the project, whose
        models are the domain model followed by an object model per satisfying instance found.
        The project is ``None`` if no satisfying instances were found or if the analysis timed out.

        The project can be written with :meth:`generate_project_file`, producing a file that
        can be imported into the web modeling editor.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            num_models: Number of satisfying instances to request from the Alloy
                Analyzer.
            seed: The seed of the random literals generated by the translator.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        result, object_models = self.generate_object_models(scope=scope, num_models=num_models, seed=seed)
        if result != AlloyResult.SAT:
            return result, None
        metadata = Metadata(description=f"Model {self.model.name} and object models of it generated with Alloy")
        return result, Project(name="Alloy_project", models=[self.model, *object_models], metadata=metadata)

    def generate_project_file(self, scope: int = 5, num_models: int = 1, seed: int = 0) -> AlloyResult:
        """Generates a B-UML project with the model and object models of it generated using Alloy
        (see :meth:`generate_project`), and writes its B-UML code to ``alloy_project.py`` in the
        output directory. Returns an AlloyResult indicating the result of the analysis. The file
        is written only if satisfying instances were found; it can be imported into the web
        modeling editor. When the solver was created without *output_dir*, the file is written to
        the solver's temporary directory, which is deleted with the solver.

        Args:
            scope: the scope of each class signature in the specification's ``run`` command.
            num_models: Number of satisfying instances to request from the Alloy
                Analyzer.
            seed: The seed of the random literals generated by the translator.

        Raises:
            AlloyTranslationError: when the model, or one of its OCL invariants, cannot be translated.
        """
        result, project = self.generate_project(scope=scope, num_models=num_models, seed=seed)
        if result == AlloyResult.SAT:
            project_to_code(project, os.path.join(self.output_dir, "alloy_project.py"))
        return result
