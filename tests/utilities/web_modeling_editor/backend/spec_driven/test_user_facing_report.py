"""The run card and BESSER_GENERATION.md never show the agent's instructions.

A run whose probes could not test its create routes used to list, under "Not
checked", each finding as the agent reads it: the payload the probe sent, the
file and line to edit, and "Use test_api ... do not remove business
validation". The report now holds one user sentence per finding.
"""
from besser.utilities.web_modeling_editor.backend.services.spec_driven.runner import (
    build_verification_report,
    run_summary_markdown,
)
from besser.spec_driven_agent.validation.issues import _check_did_not_run
from tests.spec_driven_agent.test_user_wording import (
    FORBIDDEN, _action_refused_every_state, _create_needs_customer, _create_refused, _requirement,
)


def _recipe():
    issues = ["runtime unverified: " + _create_needs_customer(),
              "runtime unverified: " + _create_refused(),
              "runtime unverified: " + _action_refused_every_state(),
              _requirement("unverified"),
              "task unverified: task 2 remains unresolved: Show open orders. Inspect and implement the "
              "required work; record exact current evidence with task_list."]
    for entity in ("Shelf", "Loan", "Member", "Fee"):
        issues.append("runtime unverified: " + _create_needs_customer()
                      .replace("/order/", f"/{entity.lower()}/").replace("Customer", entity + "Owner"))
    return {
        "target": {"kind": "backend", "description": "order desk API"},
        "requirements": [{"id": 4, "kind": "rule", "text": "An order total is never negative.",
                          "status": "unverified", "evidence": "", "note":
                          "Pydantic enforces it. [citation 1 (backend/routers/order.py): declares data]"}],
        "api_scenarios": [{"scenario_id": "order_flow", "scenario": {"requests": []},
                           "report": {"status": "failed", "error": "step 2: POST /order/ expected 201, got 422: "
                                                                   "{\"detail\": [{\"loc\": [\"body\"]}]}"}}],
        "validation_issues": [{"severity": "blocker", "message": message} for message in issues],
    }


def test_nothing_the_user_reads_is_written_for_the_agent():
    report = build_verification_report(_recipe())
    shown = [text for item in report.notVerified + report.shippedUnenforced + report.verified
             for text in (item.what, item.why or "")]
    summary = "\n".join(run_summary_markdown(_recipe(), report))

    for text in [*shown, summary]:
        assert not [fragment for fragment in FORBIDDEN if fragment in text], text
    assert "Creating order (POST /order/) could not be tested automatically" in "\n".join(shown)
    assert "The action close on Task could not be tested automatically" in "\n".join(shown)
    workflow = next(item for item in report.notVerified if item.kind == "api_workflow")
    assert workflow.what == "Test workflow 'order_flow'" and workflow.why.startswith("a test the agent wrote")


def test_the_summary_merges_repeated_kinds_and_counts_the_rest():
    report = build_verification_report(_recipe())
    summary = run_summary_markdown(_recipe(), report)
    not_checked = summary[summary.index("### Not confirmed") + 2:]

    assert any(line.startswith("- `5 create operations could not be tested automatically, because each needs "
                               "an existing record first: order, shelf, loan, member, fee.`") for line in not_checked)
    assert len(not_checked) <= 9
    total = report.counts.notVerified
    assert total == 10 and not [line for line in not_checked if "more" in line]


def test_the_next_run_reads_the_finding_and_the_user_reads_the_sentence():
    """The modify agent's notes keep the request the check sent; the recap for people does not."""
    from besser.spec_driven_agent.run_recap import build_recap, next_run_notes

    refused = "runtime unverified: " + _create_refused()
    recipe = {"instructions": "a request", "history": [{"instructions": "a request", "mode": "create"}],
              "validation_issues": [{"severity": "blocker", "message": refused},
                                    {"severity": "warning", "message":
                                        _check_did_not_run("the constructibility probe", "backend: no sandbox")}]}
    recipe["verification"] = build_verification_report(recipe).model_dump(mode="json")

    notes = next_run_notes(recipe)
    assert "autogenerated input was refused (400" in notes and "POST /invoice/" in notes
    assert "Not checked: the constructibility probe" in notes
    people = " ".join(item["text"] for item in build_recap(recipe)["open_items"])
    assert "Creating Invoice (POST /invoice/) was refused with the test data used" in people
    assert "autogenerated" not in people and "attempted input" not in people
