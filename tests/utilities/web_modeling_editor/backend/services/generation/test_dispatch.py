"""The generation service behind ``/generate-output*``, called without HTTP.

The routes only turn a ``GeneratedOutput`` into a response, so these pin what
the service hands them: the download's name, its bytes, ZIP or file, and the
service errors the routes map to 400.
"""

import asyncio
import io
import zipfile

import pytest

from besser.utilities.provenance import PROVENANCE_FILENAME
from besser.utilities.web_modeling_editor.backend.config import (
    SUPPORTED_GENERATORS,
    get_filename_for_generator,
)
from besser.utilities.web_modeling_editor.backend.models import DiagramInput, ProjectInput
from besser.utilities.web_modeling_editor.backend.routers.generation_router import _download_response
from besser.utilities.web_modeling_editor.backend.services.exceptions import ValidationError
from besser.utilities.web_modeling_editor.backend.services.generation import (
    GeneratedOutput,
    dispatch,
    generate_from_diagram,
    generate_from_project,
)

CLASS_MODEL = {
    "type": "ClassDiagram",
    "elements": {
        "class-1": {"type": "Class", "name": "Book", "attributes": ["attr-1"], "methods": []},
        "attr-1": {"type": "Attribute", "name": "+ title: str"},
    },
    "relationships": {},
}


@pytest.fixture(autouse=True)
def _isolate_cwd(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)


def _generate(generator, config=None):
    return asyncio.run(generate_from_diagram(
        DiagramInput(title="Library", model=CLASS_MODEL, generator=generator, config=config)))


def test_a_single_file_generator_gives_its_download_name_and_version_comment():
    output = _generate("python")

    assert not output.is_zip and output.media_type == "text/plain"
    assert output.file_name == get_filename_for_generator("python")
    assert output.encode_file_name
    assert output.content.startswith(b"# Generated by BESSER ")
    assert b"class Book" in output.content


def test_a_generator_option_reaches_its_builder():
    output = _generate("sqlalchemy", {"dbms": "postgresql"})

    assert output.file_name == get_filename_for_generator("sqlalchemy")
    assert b"postgresql" in output.content


def test_a_zip_generator_gives_an_archive_with_its_provenance_file():
    output = _generate("django", {"project_name": "library_site", "app_name": "books"})

    assert output.is_zip and output.media_type == "application/zip"
    assert output.file_name == get_filename_for_generator("django")
    names = zipfile.ZipFile(io.BytesIO(output.content.getvalue())).namelist()
    assert PROVENANCE_FILENAME in names
    assert any(name.startswith("library_site/") or name == "manage.py" for name in names)


def test_every_option_builder_is_a_registered_generator():
    assert set(dispatch._CLASS_DIAGRAM_BUILDERS) <= set(SUPPORTED_GENERATORS)


def test_an_unknown_generator_is_a_validation_error():
    with pytest.raises(ValidationError, match=r"^Invalid generator type: nope\. Supported types: \["):
        _generate("nope")


def test_a_project_without_a_generator_is_a_validation_error():
    project = ProjectInput(id="p", type="Project", name="P", createdAt="2026-01-01T00:00:00Z",
                           currentDiagramType="ClassDiagram", diagrams={}, settings={})

    with pytest.raises(ValidationError, match="^Generator type is required in project settings$"):
        asyncio.run(generate_from_project(project))


def test_an_invalid_supabase_user_root_is_a_validation_error():
    with pytest.raises(ValidationError, match="^Invalid user_root"):
        _generate("supabase", {"user_root": "1bad"})


class TestDownloadResponse:
    """The router's mapping of a ``GeneratedOutput`` to the HTTP response."""

    def test_a_file_name_outside_ascii_is_sent_as_rfc_6266(self):
        response = _download_response(GeneratedOutput(b"x", "数据.py", is_zip=False, encode_file_name=True))

        assert response.media_type == "text/plain"
        assert response.headers["content-disposition"] == (
            "attachment; filename=\"download.py\"; filename*=UTF-8''%E6%95%B0%E6%8D%AE.py")

    def test_a_neural_network_file_name_is_sent_as_is(self):
        response = _download_response(GeneratedOutput(b"x", "pytorch_nn_é.py", is_zip=False))

        assert response.headers["content-disposition"].encode("latin-1") == (
            'attachment; filename="pytorch_nn_é.py"'.encode("latin-1"))

    def test_a_zip_is_streamed_with_its_name(self):
        response = _download_response(GeneratedOutput(io.BytesIO(b"PK"), "django_project.zip", is_zip=True))

        assert response.media_type == "application/zip"
        assert type(response).__name__ == "StreamingResponse"
        assert response.headers["content-disposition"] == 'attachment; filename="django_project.zip"'
