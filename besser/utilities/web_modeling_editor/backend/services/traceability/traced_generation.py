"""Code generation that also returns the trace of the run.

The delivery is the one ``/generate-output`` would return: a single file with the
same name and ``Generated by BESSER`` header, or the same ZIP with its
``BESSER_GENERATION.md``. The trace's paths and line numbers refer to that delivery.
"""

import asyncio
import base64
import logging
import os
import tempfile
import uuid
from datetime import datetime, timezone
from typing import Any, Callable, Dict, List

from besser.utilities.generation_trace import FileTrace, GeneratedFile, build_generation_trace, shift_regions
from besser.utilities.provenance import add_generation_provenance_to_zip, get_besser_version, with_version_comment
from besser.utilities.web_modeling_editor.backend.config import get_filename_for_generator, get_generator_info
from besser.utilities.web_modeling_editor.backend.constants.constants import (
    DEFAULT_DBMS,
    TEMP_DIR_PREFIX,
    TRACE_MAX_STORED_CONTENT_BYTES,
    TRACED_GENERATORS,
)
from besser.utilities.web_modeling_editor.backend.models.traceability import (
    TracedGenerationInput,
    TracedGenerationResponse,
)
from besser.utilities.web_modeling_editor.backend.services.converters import (
    process_class_diagram,
    trace_buml_to_json,
)
from besser.utilities.web_modeling_editor.backend.services.exceptions import GenerationError, ValidationError
from besser.utilities.web_modeling_editor.backend.services.utils.zip_utils import zip_directory

logger = logging.getLogger(__name__)

# The generate() arguments of each traced generator, from the request config
# (the same options /generate-output passes).
_GENERATE_KWARGS: Dict[str, Callable[[Dict[str, Any]], Dict[str, Any]]] = {
    "sqlalchemy": lambda config: {"dbms": config.get("dbms", DEFAULT_DBMS)},
    "backend": lambda config: {},
}


async def generate_with_trace(input_data: TracedGenerationInput) -> TracedGenerationResponse:
    """Run a traced generator on a class diagram and return its delivery and trace fragment.

    Raises:
        ValidationError: If the generator does not support tracing, or the diagram has no id.
        ConversionError: If the diagram cannot be converted to B-UML.
        GenerationError: If a single-file generator does not write exactly one file.
    """
    generator_type = input_data.generator
    if generator_type not in TRACED_GENERATORS:
        raise ValidationError(
            f"Generator {generator_type!r} does not record traces. Traced generators: {sorted(TRACED_GENERATORS)}.")
    if not input_data.id:
        raise ValidationError("A traced generation needs the diagram id: the trace refers to the model by it.")

    domain_model = process_class_diagram(input_data.model_dump())
    info = get_generator_info(generator_type)
    file_name = get_filename_for_generator(generator_type)
    started_at = datetime.now(timezone.utc)
    with tempfile.TemporaryDirectory(prefix=f"{TEMP_DIR_PREFIX}{uuid.uuid4().hex}_") as temp_dir:
        generator = info.generator_class(domain_model, output_dir=temp_dir)
        await asyncio.to_thread(generator.generate, **_GENERATE_KWARGS[generator_type](input_data.config or {}))
        traced: Dict[str, FileTrace] = generator.traced_files
        if info.output_type == "zip":
            delivery = zip_directory(temp_dir)
            add_generation_provenance_to_zip(delivery, generator_type)
            delivered, media_type = delivery.getvalue(), "application/zip"
            files = _zip_files(temp_dir, traced)
        else:
            delivered, media_type, files = _single_file(temp_dir, generator_type, file_name, traced)
    ended_at = datetime.now(timezone.utc)

    trace = build_generation_trace(
        files,
        model_id=input_data.id,
        model_name=input_data.title.strip() or domain_model.name,
        generator=generator_type,
        generator_version=get_besser_version(),
        actor_name=input_data.actorName,
        max_stored_content_bytes=TRACE_MAX_STORED_CONTENT_BYTES,
        started_at=started_at,
        ended_at=ended_at,
    )
    return TracedGenerationResponse(
        fileName=file_name,
        mediaType=media_type,
        contentBase64=base64.b64encode(delivered).decode("ascii"),
        trace=trace_buml_to_json(trace),
    )


def _single_file(temp_dir: str, generator_type: str, file_name: str, traced: Dict[str, FileTrace]):
    """The one file delivered with its version header, and its trace shifted below the header."""
    written = os.listdir(temp_dir)
    if len(written) != 1:
        raise GenerationError(f"{generator_type} generation wrote {len(written)} files; expected one.")
    with open(os.path.join(temp_dir, written[0]), "rb") as f:
        generated = f.read()
    delivered = with_version_comment(generated, file_name)
    header_lines = delivered[:len(delivered) - len(generated)].count(b"\n")
    file_trace = traced.get(written[0], FileTrace())
    shifted = FileTrace(tuple(shift_regions(file_trace.regions, header_lines)), file_trace.sources)
    return delivered, "text/plain", [GeneratedFile(file_name, delivered.decode("utf-8"), shifted)]


def _zip_files(temp_dir: str, traced: Dict[str, FileTrace]) -> List[GeneratedFile]:
    """Every text file of a ZIP delivery (written as generated: no header), with its trace."""
    files = []
    for root, _, names in os.walk(temp_dir):
        for name in sorted(names):
            path = os.path.relpath(os.path.join(root, name), temp_dir).replace(os.sep, "/")
            with open(os.path.join(root, name), "rb") as f:
                raw = f.read()
            try:
                content = raw.decode("utf-8")
            except UnicodeDecodeError:
                # A binary file (model weights) has no lines to trace: the delivery keeps it, the trace does not.
                logger.info("Generated file %s is not text; it is left out of the trace.", path)
                continue
            files.append(GeneratedFile(path, content, traced.get(path, FileTrace())))
    return sorted(files, key=lambda f: f.path)
